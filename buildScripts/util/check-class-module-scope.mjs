import * as acorn      from 'acorn';
import {execFileSync}  from 'node:child_process';
import {readFileSync}  from 'node:fs';
import path            from 'node:path';
import process         from 'node:process';
import {fileURLToPath} from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname  = path.dirname(__filename);
const ROOT       = path.resolve(__dirname, '../..');
const BASELINE   = path.join(__dirname, 'check-class-module-scope-baseline.json');

/**
 * @module buildScripts/util/check-class-module-scope
 * @summary Keeps logic on the class where subclasses, mixins and `Neo.overwrites` can reach it, with
 * a burndown baseline.
 *
 * ## The rule, and why it is Neo-specific rather than taste
 *
 * Neo is built for extension: developers subclass, mix in, and replace class logic through
 * `Neo.overwrites`. Every one of those seams reaches a **method**. None of them can reach a
 * module-scope function — a closure beside a class is invisible to a subclass, invisible to a mixin's
 * consumer, invisible to `Neo.overwrites`, and invisible to the Neural Link's `get_method_source`.
 *
 * So the habit every other codebase teaches — "this helper does not need `this`, lift it out of the
 * class" — removes an override seam here. This is an operator ruling, not a style preference: the
 * pattern was spreading class by class, each instance locally justified.
 *
 * Module scope stays right for `import`s, constants and lookup tables, and the `Neo.setupClass`
 * export. Those are data and wiring, not behaviour anyone would override.
 *
 * ## Why the class gate, rather than a path allowlist
 *
 * A module that exports functions **and declares no class** is a different animal: `src/util/**`
 * modules that are genuinely function libraries have no class for a helper to escape from, so there
 * is nothing to override and nothing to convict. Gating on "does the program body declare a class"
 * expresses that directly and needs no allowlist to maintain — the exemption cannot drift out of date
 * because it is derived from the file rather than recorded about it.
 *
 * ## Why this parses instead of grepping
 *
 * The census this guard was built from used a line-anchored grep, and a grep answers a different
 * question than the rule asks. It cannot see `export function helper() {}` (no `function` at line
 * start), cannot see a helper indented inside a block, and cannot tell a function-valued `const` from
 * a `const` holding a lookup table whose value happens to span lines. Reading `Program.body` from the
 * parse tree asks the actual question — *is this a function binding at module scope?* — and gets the
 * same answer whatever the source formatting is.
 *
 * ## Why a baseline rather than a clean gate
 *
 * The existing hits are real and spread across unrelated subsystems; a gate failing on all of them
 * from day one is a gate somebody disables. The baseline records the debt so the **property** can be
 * asserted today: a function at module scope in a file the baseline does not cover fails, so new debt
 * cannot pass by leaving the old debt intact.
 *
 * The ratchet is symmetric, following `check-engine-brain-boundary`. A baselined entry that no longer
 * violates must also leave the baseline, or the file degrades into a list of things that used to be
 * true. This is not hypothetical here: the census this guard was built from recorded
 * `TopologyReconciler.mjs` at ten module-scope helpers, and by the time the guard was written that
 * file had migrated all ten. A baseline transcribed rather than measured ships fiction on day one,
 * which is why the initial baseline was generated by running this parser over the tree.
 */

/**
 * The tree this guard reads, as the SSOT for its own scan surface. The CI workflow's `paths:` filter
 * derives from this rather than restating it — a guard whose watched paths drift below its scanned
 * paths runs late and misattributed.
 * @type {String[]}
 */
export const SCAN_SURFACE = Object.freeze(['src/**/*.mjs']);

/**
 * The roots {@link SCAN_SURFACE} covers, in the form `git ls-files` takes.
 * @type {String[]}
 */
const SCAN_ROOTS = Object.freeze(['src']);

/**
 * @summary Is this node a function value — the thing a class method would otherwise be?
 * @param {Object} node
 * @returns {Boolean}
 */
const isFunctionValue = node => node?.type === 'FunctionExpression' || node?.type === 'ArrowFunctionExpression';

/**
 * @summary Pure predicate: which module-scope function bindings sit beside a class declaration?
 *
 * Only `Program.body` is examined, deliberately. A function nested inside another function is a local
 * concern of that function and reachable through whatever calls it; the defect this guard names is a
 * binding at **module** scope, beside a class, that no extension seam can replace.
 *
 * Covers the four shapes a helper actually takes: `function f() {}`, `const f = () => {}`,
 * `export function f() {}`, and `export const f = () => {}`. The exported forms are included because
 * the rule's reason does not care about visibility — an exported helper beside a class is exactly as
 * unreachable from a subclass as a private one — and because excluding them would leave a rename away
 * from the rule.
 *
 * Returns nothing for a file that declares no class: see the module docblock on the class gate.
 *
 * Split from the filesystem walk so the rule is unit-testable against source strings, and so a
 * red-proof can plant a helper without writing one into the tree.
 *
 * @param {String} source File contents.
 * @param {String} file Repo-relative path, used only for reporting.
 * @returns {Array<{file: String, name: String, line: Number}>}
 */
export function findModuleScopeFunctions(source, file) {
    let ast;

    try {
        ast = acorn.parse(source, {ecmaVersion: 'latest', sourceType: 'module', locations: true})
    } catch {
        // Unparseable source is not this guard's problem to report — `check-parse` owns that, and
        // failing here would convert one defect into two confusing ones.
        return []
    }

    const body = ast.body ?? [];

    const declaresClass = body.some(node =>
        node.type === 'ClassDeclaration' ||
        (node.type === 'ExportNamedDeclaration'   && node.declaration?.type === 'ClassDeclaration') ||
        (node.type === 'ExportDefaultDeclaration' && node.declaration?.type === 'ClassDeclaration')
    );

    if (!declaresClass) {
        return []
    }

    const findings = [];

    for (const node of body) {
        // `export function f() {}`, `export const f = () => {}` and `export default function f() {}`
        // all unwrap to the shapes below. The DEFAULT case is the one worth naming: it is a single
        // keyword away from the named form, reaches the class exactly as little, and an early version
        // of this guard unwrapped only `ExportNamedDeclaration` — so `export default function` was a
        // silent escape hatch until @neo-gpt-emmy's review found it.
        const isExportWrapper = (node.type === 'ExportNamedDeclaration' || node.type === 'ExportDefaultDeclaration') && node.declaration,
              statement       = isExportWrapper ? node.declaration : node;

        if (statement.type === 'FunctionDeclaration') {
            // An anonymous `export default function () {}` still binds a function at module scope; it
            // is keyed as `default` so the baseline has a stable identity for it.
            findings.push({file, name: statement.id?.name ?? 'default', line: statement.loc.start.line});
            continue
        }

        // `export default () => {}` — no declaration to unwrap, the function IS the exported expression.
        if (node.type === 'ExportDefaultDeclaration' && isFunctionValue(node.declaration)) {
            findings.push({file, name: 'default', line: node.loc.start.line});
            continue
        }

        if (statement.type === 'VariableDeclaration') {
            for (const declarator of statement.declarations) {
                if (isFunctionValue(declarator.init) && declarator.id?.type === 'Identifier') {
                    findings.push({file, name: declarator.id.name, line: declarator.loc.start.line})
                }
            }
        }
    }

    return findings
}

/**
 * Identity of a baselined helper. Deliberately `file` + `name` and NOT the line number: a line moves
 * whenever anything above it is edited, which would turn every unrelated edit into baseline churn.
 * @param {Object} entry
 * @returns {String}
 */
const helperKey = entry => `${entry.file}::${entry.name}`;

/**
 * @summary Collapses findings to one row per helper, carrying how many times it occurs.
 *
 * The count is load-bearing rather than decoration, for the reason `check-engine-brain-boundary`
 * records: a key that survives a partial burndown reports green while most of the debt is still
 * there. Two declarations sharing a name at module scope is not legal JS, so `count` is 1 in
 * practice — it is carried anyway so the two guards diff against their baselines identically, and so
 * the invariant is enforced rather than assumed.
 *
 * @param {Array<Object>} entries
 * @returns {Array<{file: String, name: String, count: Number}>}
 */
export function tallyHelpers(entries) {
    const byKey = new Map();

    for (const entry of entries) {
        const key = helperKey(entry);

        byKey.has(key)
            ? byKey.get(key).count++
            : byKey.set(key, {file: entry.file, name: entry.name, count: 1})
    }

    return [...byKey.values()].sort((a, b) => helperKey(a).localeCompare(helperKey(b)))
}

/**
 * @summary Compares live helpers against the recorded baseline, in both directions.
 *
 * @param {Array<Object>} findings Live module-scope helpers (raw, one per occurrence).
 * @param {Array<Object>} baseline Recorded, tolerated helpers (tallied, carrying `count`).
 * @returns {{added: Object[], burnedDown: Object[]}} `added` = a helper the baseline does not cover
 *          (fail up). `burnedDown` = a baselined helper that is gone (fail down — update the
 *          baseline in the same commit that migrated it).
 */
export function diffAgainstBaseline(findings, baseline) {
    const live      = tallyHelpers(findings),
          baseByKey = new Map(baseline.map(entry => [helperKey(entry), entry])),
          liveByKey = new Map(live.map(entry => [helperKey(entry), entry]));

    const added = live.filter(entry => {
        const recorded = baseByKey.get(helperKey(entry));

        return !recorded || entry.count > (recorded.count ?? 1)
    });

    const burnedDown = baseline.filter(entry => {
        const observed = liveByKey.get(helperKey(entry));

        return !observed || observed.count < (entry.count ?? 1)
    });

    return {added, burnedDown}
}

/**
 * @summary The report lines for newly-added helpers, resolved back to their raw occurrences.
 *
 * Reports from the raw findings rather than the tally: the tally drops `line` on the way, and a
 * location is the whole product of this guard. `added` is filtered from `tallyHelpers(findings)`, so
 * every key here came out of `findings` by construction and no fallback branch is reachable.
 *
 * @param {Array<Object>} added Tallied rows the baseline does not cover.
 * @param {Array<Object>} findings Raw helpers, one per occurrence, carrying `line`.
 * @returns {String[]} One line per occurrence.
 */
export function describeAddedHelpers(added, findings) {
    const addedKeys = new Set(added.map(helperKey));

    return findings
        .filter(entry => addedKeys.has(helperKey(entry)))
        .map(entry => `  ${entry.file}:${entry.line} declares ${entry.name}() at module scope`)
}

// `import.meta.url === `file://${process.argv[1]}`` is WRONG, and wrong in the worst direction: it
// percent-encodes (a checkout path containing a space yields `%20` on one side and a raw space on the
// other) and it does not resolve symlinks, so the comparison is false and this block never runs — the
// guard exits 0 having checked nothing. A gate that passes because it did not execute is the exact
// failure this file exists to prevent. Six sibling guards already use the form below; three still use
// the string form and inherit the defect.
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const files = execFileSync('git', ['ls-files', ...SCAN_ROOTS], {cwd: ROOT, encoding: 'utf8'})
        .split('\n')
        .filter(file => file.endsWith('.mjs'));

    const findings            = files.flatMap(file => findModuleScopeFunctions(readFileSync(path.join(ROOT, file), 'utf8'), file));
    const baseline            = JSON.parse(readFileSync(BASELINE, 'utf8'));
    const {added, burnedDown} = diffAgainstBaseline(findings, baseline);

    if (added.length) {
        console.error(`\x1b[31mcheck-class-module-scope: ${added.length} NEW module-scope function(s) beside a class:\x1b[0m`);
        describeAddedHelpers(added, findings).forEach(line => console.error(line));
        console.error(`
Neo is built for extension. A subclass, a mixin's consumer and \`Neo.overwrites\` can all reach a
method; none of them can reach a function at module scope, and neither can the Neural Link's
\`get_method_source\`. Move it onto the class — an instance method, a \`static\` method or a getter — or
into a dedicated \`src/util/**\` module consumed by import.

Constants and lookup tables at module scope stay fine: nobody overrides data.

Do not add a baseline entry. The baseline records debt being paid down, not a place to put new debt.`)
    }

    if (burnedDown.length) {
        console.error(`\x1b[31mcheck-class-module-scope: ${burnedDown.length} baselined entr(ies) no longer present:\x1b[0m`);
        burnedDown.forEach(entry => console.error(`  ${entry.file} no longer declares ${entry.name}() at module scope`));
        console.error(`
This is the good direction — remove them from check-class-module-scope-baseline.json in the same
commit that migrated them. A burndown baseline that only fails upward drifts above the real count,
and then it is a list of things that used to be true rather than a measurement.`)
    }

    if (added.length || burnedDown.length) {
        process.exit(1)
    }

    const fileCount = new Set(findings.map(entry => entry.file)).size;

    console.log(`check-class-module-scope: OK — ${findings.length} module-scope function(s) across ${fileCount} file(s), all baselined; ${files.length} file(s) scanned.`)
}
