import {test, expect}  from '@playwright/test';
import fs              from 'node:fs';
import os              from 'node:os';
import path            from 'node:path';
import {fileURLToPath} from 'node:url';

import {
    AGENTS_MD_SCRIPT,
    agentsMdArgs,
    isDependencyBuild,
    ensureAgentsMdFilter,
    resolvePackageBin,
    runPrepare,
    runStage
} from '../../../../buildScripts/util/prepare.mjs';
import {AGENTS_MD_CLEAN_COMMAND, AGENTS_MD_FILTER} from '../../../../buildScripts/util/agentsMdPointer.mjs';

const
    __filename      = fileURLToPath(import.meta.url),
    repoRoot        = path.resolve(path.dirname(__filename), '../../../..'),
    resolveHuskyBin = root => resolvePackageBin('husky', 'husky', root);

/**
 * @summary A checkout with a `generate-agents-md` script and an installed skills package whose
 * generator stamps its own version into the file it writes, so a spec can watch a bump move it.
 * @param {Object} options
 * @param {String} [options.script] The checkout's `generate-agents-md` script; omitted, none is declared.
 * @param {String} [options.version] The installed package version; omitted, nothing is installed.
 * @returns {String} The checkout root.
 */
function createCheckout({script, version}) {
    const root = fs.mkdtempSync(path.join(os.tmpdir(), 'prepare-spec-'));

    fs.writeFileSync(path.join(root, 'package.json'), JSON.stringify({scripts: script ? {[AGENTS_MD_SCRIPT]: script} : {}}));

    if (version) {
        installSkills(root, version)
    }

    return root
}

/**
 * @summary Installs (or bumps) the fake skills package: a manifest naming the generator's bin, and
 * a generator writing `generated by <version> for <repo>` to its `--out`.
 * @param {String} root
 * @param {String} version
 */
function installSkills(root, version) {
    const dir = path.join(root, 'node_modules', 'neo-agent-skills');

    fs.mkdirSync(dir, {recursive: true});
    fs.writeFileSync(path.join(dir, 'package.json'), JSON.stringify({version, bin: {'neo-agent-skills-agents-md': 'generate.mjs'}}));
    fs.writeFileSync(path.join(dir, 'generate.mjs'), [
        "import {readFileSync, writeFileSync} from 'node:fs';",
        'const args = process.argv.slice(2), value = flag => args[args.indexOf(flag) + 1];',
        "const {version} = JSON.parse(readFileSync(new URL('./package.json', import.meta.url), 'utf8'));",
        "writeFileSync(value('--out'), `generated by ${version} for ${value('--repo')}\\n`);"
    ].join('\n'))
}

/**
 * @summary The portable Engine prepare lifecycle: the lock-only guard short-circuits, then husky,
 * the skills materializer and the `AGENTS.md` generation run in order, and any failure fails the
 * install.
 */
test.describe('buildScripts/util/prepare — the portable prepare lifecycle', () => {
    const recordingSpawn = (results, events = []) => {
        const calls = [];
        return {
            calls,
            spawnFn: (file, args, opts) => {
                calls.push({file, args, opts});
                events.push(['spawn', path.basename(args[0] ?? file)]);
                return {status: results[calls.length - 1] ?? 0}
            }
        };
    };

    // A checkout whose filter is already registered, as on any second install
    const registeredGit = (events = []) => (root, args) => {
        events.push(['git', ...args]);

        if (args[0] === 'config' && args[2] === '--get') {
            return {status: 0, stdout: args[3].endsWith('.clean') ? AGENTS_MD_CLEAN_COMMAND : 'true'}
        }

        return args[0] === 'ls-files' ? {status: 0, stdout: '100644 0123456789abcdef 0\tAGENTS.md'} : {status: 0, stdout: ''}
    };

    test('the lock-only guard short-circuits BEFORE anything runs', () => {
        const {calls, spawnFn} = recordingSpawn([]),
              result           = runPrepare({env: {npm_config_package_lock_only: 'true'}, spawnFn});

        expect(result).toEqual({skipped: 'package-lock-only', stage: 'guard', status: 0});
        expect(calls).toEqual([]);
    });

    test('a git-dependency build skips every stage: INIT_CWD names the consumer, not this checkout', () => {
        // npm builds a `github:` dependency in a cache clone and runs its `prepare` there, with
        // INIT_CWD pointing at the directory the consumer's install was invoked from. Husky and
        // the materializer provision THIS checkout; inside someone else's install they would write
        // hooks into a cache clone and a skills façade into the consumer's root.
        const {calls, spawnFn} = recordingSpawn([]),
              result           = runPrepare({env: {INIT_CWD: os.tmpdir()}, spawnFn});

        expect(result).toEqual({skipped: 'dependency-build', stage: 'guard', status: 0});
        expect(calls).toEqual([]);
    });

    test('a workspace\'s nested install skips every stage: the root sits inside node_modules, whoever invoked npm', () => {
        // A neo-app workspace's postinstall runs `npm i` inside node_modules/neo.mjs, so INIT_CWD names this
        // package root itself. Where the root sits, not who invoked npm, says it is someone else's install.
        const tmp  = fs.mkdtempSync(path.join(os.tmpdir(), 'prepare-spec-')),
              root = path.join(tmp, 'node_modules', 'neo.mjs');

        fs.mkdirSync(root, {recursive: true});

        try {
            const {calls, spawnFn} = recordingSpawn([]),
                  result           = runPrepare({env: {INIT_CWD: root}, root, spawnFn});

            expect(result).toEqual({skipped: 'dependency-build', stage: 'guard', status: 0});
            expect(calls).toEqual([]);
            expect(isDependencyBuild({env: {}, root}), 'with no INIT_CWD at all').toBe(true);
            expect(isDependencyBuild({env: {}, root: path.join(tmp, 'node_modules_backup', 'neo.mjs')}),
                'a directory merely named like one is not').toBe(false)
        } finally {
            fs.rmSync(tmp, {force: true, recursive: true})
        }
    });

    test('the lock-only guard keeps precedence over the dependency-build guard', () => {
        const {calls, spawnFn} = recordingSpawn([]),
              result           = runPrepare({env: {INIT_CWD: os.tmpdir(), npm_config_package_lock_only: 'true'}, spawnFn});

        expect(result).toEqual({skipped: 'package-lock-only', stage: 'guard', status: 0});
        expect(calls).toEqual([]);
    });

    test('a checkout install runs every stage: INIT_CWD is this repo, literally or through a symlink', () => {
        const link = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'prepare-spec-')), 'checkout');

        fs.symlinkSync(repoRoot, link);

        try {
            for (const initCwd of [repoRoot, link]) {
                const {calls, spawnFn} = recordingSpawn([0, 0, 0]),
                      result           = runPrepare({env: {INIT_CWD: initCwd}, gitFn: registeredGit(), spawnFn});

                expect(result).toEqual({skipped: null, stage: 'agents-md', status: 0});
                expect(calls.length).toBe(3);
            }

            expect(isDependencyBuild({env: {}, root: repoRoot})).toBe(false);
            expect(isDependencyBuild({env: {INIT_CWD: link}, root: repoRoot})).toBe(false);
            expect(isDependencyBuild({env: {INIT_CWD: path.dirname(link)}, root: repoRoot})).toBe(true);
        } finally {
            fs.rmSync(path.dirname(link), {force: true, recursive: true})
        }
    });

    test('husky runs, then the skills materializer, then AGENTS.md between the filter check and the index refresh', () => {
        const events           = [],
              {calls, spawnFn} = recordingSpawn([0, 0, 0], events),
              result           = runPrepare({env: {}, gitFn: registeredGit(events), spawnFn}),
              script           = JSON.parse(fs.readFileSync(path.join(repoRoot, 'package.json'), 'utf8')).scripts[AGENTS_MD_SCRIPT];

        expect(result).toEqual({skipped: null, stage: 'agents-md', status: 0});
        expect(calls.map(call => call.args)).toEqual([
            [resolveHuskyBin(repoRoot)],
            [resolvePackageBin('neo-agent-skills', 'neo-agent-skills-materialize', repoRoot)],
            // The repository set and the output path are the script's, word for word: one declaration
            [resolvePackageBin('neo-agent-skills', 'neo-agent-skills-agents-md', repoRoot), ...script.split(/\s+/).slice(1)]
        ]);
        expect(calls[2].opts.cwd).toBe(repoRoot);
        expect(events.slice(2)).toEqual([
            // The filter must be there before the generator writes: a registered one is left alone
            ['git', 'config', '--local', '--get', `filter.${AGENTS_MD_FILTER}.clean`],
            ['git', 'config', '--local', '--get', `filter.${AGENTS_MD_FILTER}.required`],
            ['spawn', 'generate-agents-md.mjs'],
            // The entry is re-set to its own blob, so the refresh reads the file through the filter and stages nothing
            ['git', 'ls-files', '--stage', '--', 'AGENTS.md'],
            ['git', 'update-index', '--cacheinfo', '100644,0123456789abcdef,AGENTS.md'],
            ['git', 'update-index', '-q', '--refresh']
        ]);
    });

    test('the pointer filter is checked only in a git checkout, and registered when it is missing', () => {
        const plain    = fs.mkdtempSync(path.join(os.tmpdir(), 'prepare-spec-')),
              checkout = fs.mkdtempSync(path.join(os.tmpdir(), 'prepare-spec-')),
              config   = {},
              calls    = [],
              git      = args => {
                  calls.push(args);
                  if (args[2] === '--get') return {status: 0, stdout: config[args[3]] ?? ''};
                  config[args[2]] = args[3];
                  return {status: 0, stdout: ''}
              };

        fs.mkdirSync(path.join(checkout, '.git'));

        try {
            expect(ensureAgentsMdFilter({root: plain, git}), 'outside a checkout').toBe(null);
            expect(calls).toEqual([]);
            expect(ensureAgentsMdFilter({root: checkout, git})).toBe('registered');
            expect(config).toEqual({[`filter.${AGENTS_MD_FILTER}.clean`]: AGENTS_MD_CLEAN_COMMAND, [`filter.${AGENTS_MD_FILTER}.required`]: 'true'});
            expect(ensureAgentsMdFilter({root: checkout, git}), 'a second run finds it').toBe('present')
        } finally {
            [plain, checkout].forEach(root => fs.rmSync(root, {force: true, recursive: true}))
        }
    });

    test('a checkout that declares no generate-agents-md script skips the stage, and a shell-shaped one is refused', () => {
        const undeclared = createCheckout({version: '1.0.0'}),
              shellOnly  = createCheckout({script: 'neo-agent-skills-agents-md --repo "$REPOS" --out AGENTS.md', version: '1.0.0'}),
              otherBin   = createCheckout({script: 'node scripts/agents.mjs --repo neo', version: '1.0.0'});

        try {
            const {calls, spawnFn} = recordingSpawn([]);

            expect(runStage('agents-md', {root: undeclared, spawnFn})).toEqual({skipped: 'not-declared', stage: 'agents-md', status: 0});
            expect(calls).toEqual([]);
            expect(agentsMdArgs(path.join(undeclared, 'missing')), 'no package.json at all').toBe(null);
            expect(() => runStage('agents-md', {root: shellOnly, spawnFn})).toThrow(/must be a plain call of neo-agent-skills-agents-md, found '.*\$REPOS/);
            expect(() => runStage('agents-md', {root: otherBin, spawnFn})).toThrow(/must be a plain call/);
            expect(calls).toEqual([])
        } finally {
            [undeclared, shellOnly, otherBin].forEach(root => fs.rmSync(root, {force: true, recursive: true}))
        }
    });

    test('a bump moves the file: the stage writes what the installed version generates', () => {
        const root = createCheckout({script: 'neo-agent-skills-agents-md --repo neo,neo-agent-brain --out AGENTS.md', version: '1.3.3'}),
              read = () => fs.readFileSync(path.join(root, 'AGENTS.md'), 'utf8');

        try {
            expect(runStage('agents-md', {root, env: {}})).toEqual({skipped: null, stage: 'agents-md', status: 0});
            expect(read()).toBe('generated by 1.3.3 for neo,neo-agent-brain\n');

            installSkills(root, '1.3.5');

            expect(runStage('agents-md', {root, env: {}})).toEqual({skipped: null, stage: 'agents-md', status: 0});
            expect(read()).toBe('generated by 1.3.5 for neo,neo-agent-brain\n')
        } finally {
            fs.rmSync(root, {force: true, recursive: true})
        }
    });

    test('a husky failure fails the install before the materializer runs', () => {
        const {calls, spawnFn} = recordingSpawn([1]),
              result           = runPrepare({env: {}, spawnFn});

        expect(result).toEqual({skipped: null, stage: 'husky', status: 1});
        expect(calls.length).toBe(1);
    });

    test('a materializer failure fails the install before AGENTS.md is generated', () => {
        const {calls, spawnFn} = recordingSpawn([0, 1]),
              result           = runPrepare({env: {}, spawnFn});

        expect(result).toEqual({skipped: null, stage: 'materialize', status: 1});
        expect(calls.length).toBe(2);
    });

    test('a failed AGENTS.md generation fails the install, and the index is not touched', () => {
        const events           = [],
              {calls, spawnFn} = recordingSpawn([0, 0, 1], events),
              result           = runPrepare({env: {}, gitFn: registeredGit(events), spawnFn});

        expect(result).toEqual({skipped: null, stage: 'agents-md', status: 1});
        expect(calls.length).toBe(3);
        expect(events.some(([kind, command]) => kind === 'git' && command === 'update-index')).toBe(false);
    });

    test('a filter that cannot be registered stops the stage before AGENTS.md is written', () => {
        // `git config` fails to write, e.g. while `.git/config.lock` is held: every read still finds nothing
        const {calls, spawnFn} = recordingSpawn([0, 0, 0]),
              gitFn            = (root, args) => ({status: args[2] === '--get' ? 1 : 255, stdout: ''});

        expect(() => runPrepare({env: {}, gitFn, spawnFn})).toThrow(/cannot register filter\.neo-agents-md\.clean and filter\.neo-agents-md\.required, so AGENTS\.md is left as it is/);
        expect(calls.map(call => path.basename(call.args[0]))).toEqual([path.basename(resolveHuskyBin(repoRoot)), path.basename(resolvePackageBin('neo-agent-skills', 'neo-agent-skills-materialize', repoRoot))])
    });

    test('a manifest without the named bin entry is a named error, even when it declares others', () => {
        const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'prepare-spec-'));

        fs.mkdirSync(path.join(dir, 'node_modules', 'neo-agent-skills'), {recursive: true});
        fs.writeFileSync(path.join(dir, 'node_modules', 'neo-agent-skills', 'package.json'), JSON.stringify({bin: {'neo-agent-skills-secrets': 'secrets.mjs'}}));

        try {
            expect(() => resolvePackageBin('neo-agent-skills', 'neo-agent-skills-materialize', dir)).toThrow(/declares no bin entry 'neo-agent-skills-materialize'/);
        } finally {
            fs.rmSync(dir, {force: true, recursive: true})
        }
    });

    test('a missing husky entrypoint is a named error, not an opaque spawn failure', () => {
        const empty = fs.mkdtempSync(path.join(os.tmpdir(), 'prepare-spec-'));

        try {
            expect(() => resolveHuskyBin(empty)).toThrow(/husky package not found/);
        } finally {
            fs.rmSync(empty, {force: true, recursive: true})
        }
    });

    test('a husky package declaring no bin entry is a named error', () => {
        const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'prepare-spec-'));

        fs.mkdirSync(path.join(dir, 'node_modules', 'husky'), {recursive: true});
        fs.writeFileSync(path.join(dir, 'node_modules', 'husky', 'package.json'), '{}');

        try {
            expect(() => resolveHuskyBin(dir)).toThrow(/declares no bin entry/);
        } finally {
            fs.rmSync(dir, {force: true, recursive: true})
        }
    });

    test('a corrupt husky manifest is a named parse error, matching its neighbours', () => {
        const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'prepare-spec-'));

        fs.mkdirSync(path.join(dir, 'node_modules', 'husky'), {recursive: true});
        fs.writeFileSync(path.join(dir, 'node_modules', 'husky', 'package.json'), '{not json');

        try {
            expect(() => resolveHuskyBin(dir)).toThrow(/cannot parse husky's package\.json/);
        } finally {
            fs.rmSync(dir, {force: true, recursive: true})
        }
    });

    test('a bin target missing from disk is a named error naming the entry', () => {
        const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'prepare-spec-'));

        fs.mkdirSync(path.join(dir, 'node_modules', 'husky'), {recursive: true});
        fs.writeFileSync(path.join(dir, 'node_modules', 'husky', 'package.json'), JSON.stringify({bin: {husky: 'bin.js'}}));

        try {
            expect(() => resolveHuskyBin(dir)).toThrow(/'bin\.js' not found/);
        } finally {
            fs.rmSync(dir, {force: true, recursive: true})
        }
    });

    test('a failure-to-launch throws with the error code — never a bare exit 1 with no diagnostic', () => {
        // spawnSync signals failure-to-launch through `error`, not `status`: reading only `status`
        // maps it to 1 with zero output, the same invisibility class this module exists to remove.
        const spawnFn = () => ({error: Object.assign(new Error('spawn node ENOENT'), {code: 'ENOENT'}), status: null});

        expect(() => runPrepare({env: {}, spawnFn})).toThrow(/failed to launch.*ENOENT/);
    });

    test('every entrypoint resolves from its package\'s own bin declaration on this host', () => {
        // The resolution is read from each manifest, not hardcoded — and all three exist here.
        expect(fs.existsSync(resolveHuskyBin(repoRoot))).toBe(true);
        expect(fs.existsSync(resolvePackageBin('neo-agent-skills', 'neo-agent-skills-materialize', repoRoot))).toBe(true);
        expect(fs.existsSync(resolvePackageBin('neo-agent-skills', 'neo-agent-skills-agents-md', repoRoot))).toBe(true);
    });
});
