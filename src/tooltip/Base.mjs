import Container from '../container/Base.mjs';
import Label     from '../component/Label.mjs';
import VDomUtil  from '../util/VDom.mjs';

let
    // When the last shown tooltip of each browser window hid, by windowId
    hiddenAt   = {},
    // Settles once the retired tooltips of each browser window are out of the DOM, by windowId
    leaving    = {},
    // The shared tooltip of each browser window, by windowId
    singletons = {},
    // The visible tooltip of each browser window, by windowId: showing one hides the other
    visible    = {};

/**
 * @summary Base class for component tooltips.
 * @description Where the pointer goes decides when a tooltip hides, not a timer. Leaving the target for the tooltip
 * keeps a hoverable tooltip ({@link #stayOnHover}) up, as WCAG 2.1 SC 1.4.13 asks of content that opens on hover:
 * its hit area spans the gap to its target, so the pointer crosses into it directly. Leaving the target, or the
 * tooltip, for anywhere else hides it after {@link #retargetWindow}, or after an explicit {@link #hideDelay}; entering
 * another of its targets in that window retargets the shown tooltip instead. A browser window shows one tooltip at a
 * time: the next one enters the DOM once the last one left it. While another one shows or for {@link #warmWindow} ms
 * after one hid, the next target shows its tooltip without {@link #showDelay}, so moving along neighbouring targets
 * stays prompt. The keyboard reaches the same targets: focus on one shows its tooltip, and focus leaving it or Escape
 * hides it.
 * @class Neo.tooltip.Base
 * @extends Neo.container.Base
 */
class Tooltip extends Container {
    static config = {
        /**
         * @member {String} className='Neo.tooltip.Base'
         * @protected
         */
        className: 'Neo.tooltip.Base',
        /**
         * @member {String} ntype='tooltip'
         * @protected
         */
        ntype: 'tooltip',
        /**
         * @member {String[]} baseCls=['neo-tooltip']
         */
        baseCls: ['neo-tooltip'],
        /**
         * A reference to the target component which is supposed to show this tooltip on mouseenter
         * @member {String|null} componentId_=null
         * @reactive
         */
        componentId_: null,
        /**
         * Delegates down to a CSS selector inside the target component
         * @member {String|null} delegate=null
         */
        delegate: null,
        /**
         * The delay in ms before the tooltip gets hidden while hovering the target element.
         * Use null to disable the dismiss logic.
         * @member {Number|null} dismissDelay=10000
         */
        dismissDelay: 10000,
        /**
         * The dismissDelay task id generated by setTimeout()
         * @member {Number|null} dismissDelayTaskId=null
         * @protected
         */
        dismissDelayTaskId: null,
        /**
         * @member {Boolean} floating=true
         */
        floating: true,
        /**
         * The delay in ms before the tooltip hides once the pointer left its target, or the tooltip, for anywhere
         * else. null leaves only {@link #retargetWindow}, and 0 hides it at once; a hoverable tooltip needs no delay
         * to be reached, since its hit area spans the gap.
         * @member {Number|null} hideDelay=null
         */
        hideDelay: null,
        /**
         * The showDelay task id generated by setTimeout()
         * @member {Number|null} hideDelayTaskId=null
         * @protected
         */
        hideDelayTaskId: null,
        /**
         * How long in ms a departure waits for the pointer to enter another target of this tooltip before the tooltip
         * hides: a leave and the next target's enter arrive as two events, and the enter then retargets the shown
         * tooltip instead of mounting it again. A {@link #hideDelay}, 0 included, replaces it.
         * @member {Number} retargetWindow=40
         */
        retargetWindow: 40,
        /**
         * The delay in ms before the tooltip gets shown
         * @member {Number|null} showDelay=200
         */
        showDelay: 200,
        /**
         * The showDelay task id generated by setTimeout()
         * @member {Number|null} showDelayTaskId=null
         * @protected
         */
        showDelayTaskId: null,
        /**
         * True prevents the tooltip from hiding while the mouse cursor is above it
         * @member {Boolean|null} stayOnHover_=true
         * @reactive
         */
        stayOnHover_: true,
        /**
         * For this long in ms after a tooltip of the same browser window hid, a target shows its tooltip without
         * {@link #showDelay}
         * @member {Number} warmWindow=300
         */
        warmWindow: 300
    }

    /**
     * The listeners this tooltip holds on each component it delegates from, by component id. A destroyed component
     * takes its listeners along; its entry goes at the next registration.
     * @member {Map<String, {listeners: Object[], root: Neo.component.Base}>} #delegations
     */
    #delegations = new Map()
    /**
     * DOM id of the currently hovered delegated target (`Neo` component id or raw `[data-neo-tooltip]` VDOM id).
     * Tracked separately from `activeTarget` because `Neo.get()` resolves component instances only.
     * @member {String|null} activeTargetId=null
     * @protected
     */
    activeTargetId = null
    /**
     * True once Main aligned the shown tooltip, which lifts its paint gate (`Base.css`), until it retires. Mounted is
     * not painted: an insert lands hidden, and only an alignment shows it.
     * @member {Boolean} painted=false
     * @protected
     */
    painted = false
    /**
     * A fresh object per {@link #retire}: an alignment Main answers after the latest one served a show that is over
     * @member {Object|null} retirement=null
     * @protected
     */
    retirement = null

    /**
     * A tooltip lies outside its targets' component paths, and focus events stop at the focused component
     * (`Neo.manager.DomEvent#fire`): it hears focus and keys at its window's body.
     * @param {Object} config
     */
    construct(config) {
        super.construct(config);

        let me = this;

        me.addDomListeners([
            {focusin : me.onTargetFocusIn,   scope: me, vnodeId: 'document.body'},
            {focusout: me.onTargetFocusOut,  scope: me, vnodeId: 'document.body'},
            {keydown : me.onDocumentKeyDown, scope: me, vnodeId: 'document.body'}
        ])
    }

    /**
     * @summary Listens for the delegated mouseenter and mouseleave on a component, once per instance. A target must lie
     * inside such a component: an event reaches a listener only along the target's parent chain, and
     * `Neo.manager.DomEvent.verifyMouseEnterLeave()` looks for the target in the listening component's vdom.
     * A component answers to one shared tooltip, the one of its window: a shared tooltip that takes a component
     * releases it from the others, so a component that moved to another window stops reaching the tooltip it left.
     * @param {Neo.component.Base} component
     */
    addDelegationRoot(component) {
        let me          = this,
            delegations = me.#delegations,
            listeners;

        if (!component || delegations.get(component.id)?.root === component) {
            return
        }

        delegations.forEach((entry, id) => entry.root.isDestroyed && delegations.delete(id));

        me.isShared && Object.values(singletons).forEach(tooltip => tooltip !== me && tooltip.removeDelegationRoot(component));

        // One listener per event: `Neo.manager.DomEvent` removes a listener under a single event name
        listeners = [
            {mouseenter: me.onDelegateMouseEnter, delegate: me.delegate, scope: me},
            {mouseleave: me.onDelegateMouseLeave, delegate: me.delegate, scope: me}
        ];

        delegations.set(component.id, {listeners, root: component});
        component.addDomListeners(listeners)
    }

    /**
     * Arms one of the named delays, replacing a pending timer of the same name.
     * @param {String} id valid values: dismiss, hide, show
     * @param {Function} callback
     * @param {Number} delay
     */
    addTimeout(id, callback, delay) {
        this.clearTimeout(id);
        this[id + 'DelayTaskId'] = setTimeout(callback, delay)
    }

    /**
     * Triggered after the componentId config got changed
     * @param {String} value
     * @param {String} oldValue
     * @protected
     */
    afterSetComponentId(value, oldValue) {
        if (oldValue) {
            // todo: remove the component domListeners
        }

        value && this.addDelegationRoot(Neo.getComponent(value))
    }

    /**
     * Triggered after the stayOnHover config got changed
     * @param {Boolean} value
     * @param {Boolean} oldValue
     * @protected
     */
    afterSetStayOnHover(value, oldValue) {
        if (oldValue) {
            // todo: remove the component domListeners
        }

        // The hit area that spans the gap to the target
        this.toggleCls('neo-tooltip-hoverable', !!value);

        if (value) {
            let me = this;

            me.addDomListeners([
                {mouseenter: me.onMouseEnter, scope: me},
                {mouseleave: me.onMouseLeave, scope: me}
            ])
        }
    }

    /**
     * Triggered after the text config got changed
     * @param {Boolean} value
     * @param {Boolean} oldValue
     * @protected
     */
    afterSetText(value, oldValue) {
        if (value) {
            let me    = this,
                items = me.items || [],
                item  = items[0];

            if (item?.ntype === 'label') {
                item.text = value
            } else {
                me.add({
                    module: Label,
                    text  : value
                })
            }
        }
    }

    /**
     * Aligns a tooltip that is still meant to show, which paints it. One hidden while its insert was on its way lands
     * in the DOM unaligned, which keeps it out of sight (`Base.css`) until its landing removes it. An alignment that
     * Main answers after a retirement painted nothing, also when the tooltip shows again meanwhile.
     * @param {Object} [spec={}]
     * @returns {Promise<void>}
     */
    async alignTo(spec={}) {
        let me           = this,
            {retirement} = me;

        if (!me._hidden) {
            await super.alignTo(spec);

            me.retirement === retirement && !me._hidden && (me.painted = true)
        }
    }

    /**
     * Clears one or multiple setTimeout call(s)
     * @param {String[]|String} timers valid values: dismiss, hide, show
     */
    clearTimeout(timers) {
        if (!Array.isArray(timers)) {
            timers = [timers]
        }

        let me = this,
            id;

        timers.forEach(timer => {
            id = timer + 'DelayTaskId';

            if (me[id]) {
                clearTimeout(me[id]);
                me[id] = null
            }
        })
    }

    /**
     * @summary The shared tooltip of a browser window: one element per document serves every app the window hosts,
     * and it renders where its targets are. Each app anchors its main view in its own window, which carries the
     * `data-neo-tooltip` targets that no component announces; a component target announces its root through
     * {@link #delegateFromRootOf}. The tooltip leaves with its window.
     * @param {Neo.controller.Application} app
     * @param {Number|String} [windowId=app.mainView.windowId]
     * @returns {Neo.tooltip.Base}
     */
    static createSingleton(app, windowId=app.mainView.windowId) {
        let tooltip = singletons[windowId];

        if (!tooltip || tooltip.isDestroyed) {
            tooltip = singletons[windowId] = Neo.create('Neo.tooltip.Base', {
                appName  : app.name,
                delegate : this.delegateFilter,
                isShared : true,
                resetCfg : {},
                windowId,
                listeners: {
                    // Reconfigure on over a target
                    targetOver(event) {
                        Tooltip.applySingletonTargetConfig(this, event)
                    }
                }
            });

            Neo.currentWorker.on('disconnect', tooltip.onWindowDisconnect, tooltip)
        }

        // A main view still under construction is its config, which may carry the windowId already
        let {mainView} = app;

        mainView instanceof Neo.component.Base && mainView.windowId === windowId && tooltip.addDelegationRoot(mainView);

        return tooltip
    }

    /**
     * @summary Lets the shared tooltip of a target's window reach the target wherever it lies, such as in a dialog
     * under `document.body`: the tooltip listens on the target's root, the top of its `parentId` chain.
     * @param {Neo.component.Base} target A mounted component that uses the shared tooltip
     */
    static delegateFromRootOf(target) {
        let {app} = target;

        app && this.createSingleton(app, target.windowId).addDelegationRoot(Neo.manager.Component.getParents(target).at(-1) || target)
    }

    /**
     * A tooltip cancels its pending delays and stops listening on its components. A shared one also stops following
     * window departures and leaves the registry.
     * @param {...*} args
     */
    destroy(...args) {
        let me = this;

        me.clearTimeout(['dismiss', 'hide', 'show']);
        visible[me.windowId] === me && delete visible[me.windowId];

        me.#delegations.forEach(({root}) => me.removeDelegationRoot(root));

        if (me.isShared) {
            Neo.currentWorker.un('disconnect', me.onWindowDisconnect, me);
            singletons[me.windowId] === me && delete singletons[me.windowId]
        }

        super.destroy(...args)
    }

    /**
     * @summary Reconfigures the shared tooltip from the active delegated target, including the closest
     * nested theme so a viewport-owned singleton visually follows the hovered component scope.
     * @param {Neo.tooltip.Base} tooltip
     * @param {Object} event
     * @param {Neo.component.Base} [event.target]
     * @param {Object} event.data
     * @returns {Object} The config applied to the singleton.
     */
    static applySingletonTargetConfig(tooltip, {target, data} = {}) {
        let delegatedNode = data?.currentTarget && data?.path?.find?.(node => node.id === data.currentTarget) || data?.target,
            config        = target?._tooltip ? {...target._tooltip} : {text: delegatedNode?.data?.neoTooltip},
            theme         = this.resolveTargetTheme(target, data),
            key;

        // Revert last pointerOver config set to initial setting.
        tooltip.setSilent(tooltip.resetCfg);
        tooltip.resetCfg = {};

        // Explicit tooltip configs remain authoritative; otherwise inherit the active target theme.
        if (theme && !config.theme) {
            config.theme = theme
        }

        // Cache things we have to reset.
        for (key in config) {
            tooltip.resetCfg[key] = tooltip[key]
        }

        // Set ourself up as the target wants.
        tooltip.set(config);

        return config
    }

    // Used as a delegate filter to activate on targets which have a tooltip configuration
    static delegateFilter(path) {
        for (let i = 0, { length } = path; i < length; i++) {
            if (path[i].cls.includes('neo-uses-shared-tooltip') || path[i].data['neoTooltip']) {
                return i
            }
        }
    }

    /**
     * @summary Returns the closest theme for a shared-tooltip target: first via component ownership,
     * then via the delegated DOM path for data-attribute tooltips.
     * @param {Neo.component.Base} target
     * @param {Object} data
     * @returns {String|undefined}
     */
    static resolveTargetTheme(target, data) {
        let theme = target?.getTheme?.();

        if (theme) {
            return theme
        }

        for (const node of data?.path || []) {
            theme = node.cls?.find?.(item => item.startsWith('neo-theme-'));

            if (theme) {
                return theme
            }
        }
    }

    /**
     * @summary The target a DOM event path names for this tooltip, matched as its pointer listeners match one: under one
     * of its delegation roots, by its {@link #delegate}, or the root itself without one.
     * @param {Object[]} path
     * @returns {String|null}
     * @protected
     */
    getTargetId(path) {
        let me            = this,
            componentPath = Neo.manager.Component.getParentPath(path.map(node => node.id)),
            targetId, vnodeId;

        for (const {root} of me.#delegations.values()) {
            if (!root.isDestroyed && componentPath.includes(root.id)) {
                vnodeId  = root.vdom?.id || root.id;
                targetId = Neo.manager.DomEvent.verifyDelegationPath({delegate: me.delegate || '#' + vnodeId, vnodeId}, path, componentPath);

                if (targetId) {
                    return targetId
                }
            }
        }

        return null
    }

    /**
     * @summary Hides a mounted tooltip or records the hidden intent for its pending mount flight. Only a tooltip that
     * was painted warms its window for {@link #warmWindow}.
     */
    hide() {
        this.retire()
    }

    /**
     * {@link #hide}, for the next tooltip of the window to wait on. `hide()` itself returns nothing, so a remote caller
     * never waits on a held insert. The window stays held until the node is out of the DOM: a tooltip shown in the
     * meantime waits on the window's `leaving` entry, also after this one left the window's visible slot.
     * @returns {Promise|null} Settles once the tooltip's node is out of the DOM, also when its mount flight lands first
     * @protected
     */
    retire() {
        let me         = this,
            {windowId} = me;

        me.clearTimeout(['dismiss', 'hide', 'show']);

        me.painted && (hiddenAt[windowId] = Date.now());
        visible[windowId] === me && delete visible[windowId];

        // An alignment still on its way may land before the removal below and lift the paint gate (`Base.css`): a call
        // on the alignment's own channel hides the unpainted tooltip first
        me.mounted && !me.painted && Neo.main.DomAccess.setStyle({id: me.id, style: {visibility: 'hidden'}, windowId});

        me._hidden        = true;
        me.activeTarget   = null;
        me.activeTargetId = null;
        me.painted        = false;
        me.retirement     = {};

        let out = me.mounted ? me.unmount() : me.mountFlight;

        if (out) {
            let held = Promise.all([leaving[windowId], Promise.resolve(out).catch(Neo.emptyFn)]);

            leaving[windowId] = held;
            held.then(() => leaving[windowId] === held && delete leaving[windowId])
        }

        return out
    }

    /**
     * Hides the tooltip after its hideDelay, or else after its retargetWindow. A tooltip not painted yet hides at once,
     * so a departure before the first paint cancels the show.
     * @param {Object|null} data
     */
    hideDelayed(data) {
        let me    = this,
            delay = me.painted ? me.hideDelay ?? me.retargetWindow : 0;

        if (delay) {
            me.addTimeout('hide', me.hide.bind(me), delay)
        } else {
            me.hide(data)
        }
    }

    /**
     * @param {Object} data
     */
    onDelegateMouseEnter(data) {
        let me              = this,
            {currentTarget} = data;

        // If it's an internal move within the delegate, do nothing
        if (currentTarget !== me.activeTargetId) {
            me.activeTargetId = currentTarget;
            me.activeTarget   = Neo.get(currentTarget) || null;

            // Allow listeners (eg the Tooltip singleton) which is shared between all Components
            // listens for this in order to reconfigure itself from the activeTarget.
            // So this event must be fired before the alignment is set up.
            me.fire('targetOver', {
                target : me.activeTarget,
                data
            });

            // An own tooltip renders under the document body, outside its target's themed root, so it wears the
            // target's theme, as the shared one does through `applySingletonTargetConfig()`
            me.isShared || (me.theme = Tooltip.resolveTargetTheme(me.activeTarget, data) || me.theme);

            me.align.target = currentTarget;
            me.align.targetMargin = 10;
            // Main writes the gap at every alignment, its own resyncs included, for the hit area to span it (`Base.css`)
            me.align.exposeGap = true;

            // Still visible, just realign
            if (me.mounted) {
                me.show();
                me.alignTo()
            } else {
                me.showDelayed(data)
            }
        }
    }

    /**
     * @param {Object} data
     */
    onDelegateMouseLeave(data) {
        let me = this;

        // If it's an internal move within the delegate, do nothing
        if (data.currentTarget === me.activeTargetId) {
            me.fire('targetOut', {
                target : me.activeTarget,
                data
            });

            me.activeTarget   = null;
            me.activeTargetId = null;
            // a show still pending would fire after the leave and cancel the hide
            me.clearTimeout('show');

            // Into a hoverable tooltip it stays, anywhere else it goes
            if (!(me.stayOnHover && me.mounted && Tooltip.nodeIsIn(data.relatedTarget, me))) {
                me.hideDelayed(data)
            }
        }
    }

    /**
     * Escape hides the tooltip that shows or is about to, as WCAG 2.1 SC 1.4.13 asks of content that opens on hover or
     * focus
     * @param {Object} data
     */
    onDocumentKeyDown(data) {
        let me = this;

        data.key === 'Escape' && (me.activeTargetId || me.mounted) && me.hide()
    }

    /**
     * Keyboard focus on a target shows its tooltip, as the pointer entering it does
     * @param {Object} data
     */
    onTargetFocusIn(data) {
        let currentTarget = this.getTargetId(data.path);

        currentTarget && this.onDelegateMouseEnter({...data, currentTarget})
    }

    /**
     * Focus leaving a target hides its tooltip, as the pointer leaving it does. A move between two nodes of the target
     * keeps it.
     * @param {Object} data
     */
    onTargetFocusOut(data) {
        let me            = this,
            currentTarget = me.getTargetId(data.path);

        currentTarget && !me.isNodeInTarget(data.relatedTarget, currentTarget) && me.onDelegateMouseLeave({...data, currentTarget})
    }

    /**
     * mouseenter event listener for the tooltip element: it keeps a tooltip that stays on hover. A shared tooltip keeps
     * this listener after a target turns stayOnHover off, and then lets the departure run.
     * @param {Object} data
     */
    onMouseEnter(data) {
        let me       = this,
            targetId = data.path[0].id;

        // only use path[0] based events to ignore mouseenter & leave for child nodes
        me.id === targetId && me.stayOnHover && me.clearTimeout(['dismiss', 'hide'])
    }

    /**
     * @summary True if a DOM node lies inside the aligned target, whether that target is a `Neo.component.Base`
     * instance or a raw `[data-neo-tooltip]` VDOM subtree under one of this tooltip's delegation roots (`VDomUtil.find`
     * expands `{componentId}` references by default, so targets inside child components are reached too).
     * @param {Object|undefined} node
     * @param {String|null|undefined} targetId
     * @returns {Boolean}
     * @protected
     */
    isNodeInTarget(node, targetId) {
        let me = this,
            id = node?.id;

        if (!id || !targetId) {
            return false
        }

        if (id === targetId || Tooltip.nodeIsIn(node, Neo.getComponent(targetId))) {
            return true
        }

        for (const {root} of me.#delegations.values()) {
            let targetSubtree = !root.isDestroyed && root.vdom && VDomUtil.find(root.vdom, targetId);

            if (targetSubtree?.vdom && VDomUtil.find(targetSubtree.vdom, id)) {
                return true
            }
        }

        return false
    }

    /**
     * mouseleave event listener for the tooltip element. Back onto its target the tooltip stays, since the target's
     * enter shows it again, and so does a move within the tooltip: Chromium reports a crossing from the hit area that
     * spans the gap into the tooltip's own box as a leave whose `relatedTarget` is the tooltip itself. Anywhere else
     * it goes.
     * @param {Object} data
     */
    onMouseLeave(data) {
        let me              = this,
            {relatedTarget} = data,
            target          = me.align?.target,
            targetId        = data.path[0].id,
            stays           = Tooltip.nodeIsIn(relatedTarget, me) || me.isNodeInTarget(relatedTarget, target);

        // only use path[0] based events to ignore mouseenter & leave for child nodes
        me.id === targetId && !stays && me.hideDelayed(null)
    }

    /**
     * A shared tooltip leaves with its window. The window's apps are reaped without it, since it lies in no app's
     * component tree, and a SharedWorker retires the window's last port before it fires `disconnect`.
     * @param {Object} data
     * @param {Number|String} data.windowId
     */
    onWindowDisconnect({windowId}) {
        if (windowId === this.windowId && !Neo.currentWorker.ports?.some(port => port.windowId === windowId)) {
            this.destroy()
        }
    }

    /**
     * True if a DOM node lies inside a component: its root, a node of its vdom, or a node of a child component's
     * @param {Object|undefined} node A DOM event's node, such as a mouseleave's `relatedTarget`
     * @param {Neo.component.Base|null|undefined} component
     * @returns {Boolean}
     */
    static nodeIsIn(node, component) {
        let id = node?.id;

        return !!(id && component && (id === component.id || VDomUtil.find(component.vdom, id)))
    }

    /**
     * Stops listening on a component this tooltip delegates from
     * @param {Neo.component.Base} component
     */
    removeDelegationRoot(component) {
        let me    = this,
            entry = me.#delegations.get(component.id);

        if (entry?.root === component) {
            me.#delegations.delete(component.id);

            component.isDestroyed || component.removeDomListeners(entry.listeners)
        }
    }

    /**
     * @summary Shows the tooltip in one mount flight, which lands on the latest visibility intent. The tooltip its
     * window showed before hides, and this one enters the DOM only once every retired tooltip of the window has left
     * it, so a window never holds two.
     * @param {Object} data
     */
    show(data) {
        let me    = this,
            shown = visible[me.windowId];

        shown && shown !== me && !shown.isDestroyed && shown.retire();

        let gone = leaving[me.windowId];

        visible[me.windowId] = me;

        me.showDelayTaskId = null;

        me.clearTimeout(['hide', 'dismiss']);

        if (me.dismissDelay) {
            me.addTimeout('dismiss', me.hide.bind(me), me.dismissDelay, data)
        }

        if (!me.mounted && !me.mountFlight) {
            me.startMountFlight(gone
                ? gone.then(() => me._hidden || me.isDestroyed ? null : me.initVnode(true))
                : me.initVnode(true))
        }

        me._hidden = false
    }

    /**
     * Shows the tooltip using the given showDelay, or at once while another tooltip of its window is painted or one hid
     * less than {@link #warmWindow} ago
     * @param {Object} data
     */
    showDelayed(data) {
        let me    = this,
            shown = visible[me.windowId],
            warm  = shown && shown !== me && shown.painted || Date.now() - (hiddenAt[me.windowId] ?? -Infinity) < me.warmWindow;

        if (me.showDelay && !warm) {
            me.addTimeout('show', me.show.bind(me), me.showDelay)
        } else {
            me.show(data)
        }
    }
}

export default Neo.setupClass(Tooltip);
