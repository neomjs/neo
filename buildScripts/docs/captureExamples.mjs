/**
 * @module buildScripts.docs.captureExamples
 * @summary Captures catalog examples, without Brain or private services. A covered record without a recipe is
 * captured from the frame a visitor lands on: one viewport, the whole frame, and a wait for that frame to settle.
 * The recipes are frozen: an example that needs a state for its cover shows it on landing, set in its own code.
 * @example node buildScripts/docs/captureExamples.mjs --base-url http://localhost:8080 --record grid-cell-editing
 * @example node buildScripts/docs/captureExamples.mjs --family grid-table --preview
 * @example node buildScripts/docs/captureExamples.mjs --tiles
 * A tile crops one workbench entry's component on its dark theme (neo-dark where configured) and again on its light
 * theme as the `-light` partner, both in one tile-aspect region that holds the component in either theme, or fails
 * when that crop would cut the component. A manifest entry `{path, width, height}` gives the component that
 * size for its capture, so a wide one stays legible at the tile's width. Entries that render the current date or time differ between runs:
 * the App worker keeps the real clock.
 * Start the local dev server first. Output defaults to a fresh test-results/example-covers run.
 * Preview routes generated bytes only; it neither edits the catalog nor proves Pages deployment.
 */
const ROOT           = fileURLToPath(new URL('../../', import.meta.url)),
    PAGES_PREFIX     = 'https://raw.githubusercontent.com/neomjs/pages/main/resources_pub/website/examples/',
    WIDTH            = 640, HEIGHT = 360, DPR = 2, MAX_BYTES = 150000,
    QUALITIES        = [90, 85, 80],
    STEP_KINDS       = new Set(['click', 'dblclick', 'fill', 'press', 'scroll', 'wait']),
    TILE_VIEWPORT    = {width: 1440, height: 900}, TILE_MIN = {width: 160, height: 120}, TILE_PADDING = 24,
    FILENAME_ID      = /^[a-zA-Z0-9_-]+$/,
    LANDING          = {viewport: {width: 960, height: 540}, theme: 'dark', state: 'The frame a visitor lands on.', ready: [], steps: [], after: [], region: 'viewport'},
    LANDING_QUIET_MS = 1000,
    NETWORK_QUIET_MS = 500,
    // The Portal shows a cover or tile in its own theme: the dark image keeps the base file name, its light partner adds
    // `-light` before the extension. A pass asks for its first theme and takes any of its themes, as an example or a
    // workbench may offer only the legacy one; a frame in another scheme is no image of this pass
    PAIR_THEMES      = [
        {scheme: 'dark',  variant: '',       themes: ['neo-theme-neo-dark',  'neo-theme-dark']},
        {scheme: 'light', variant: '-light', themes: ['neo-theme-neo-light', 'neo-theme-light']}
    ];

/**
 * @summary The link a landing capture opens: the record's devmode URL with `?theme=` set, as the catalog in that theme
 * opens an example, so the cover shows the theme a visitor lands on.
 * @param {String} devmode The record's `urls.devmode`, relative to the base URL
 * @param {String} theme The Neo theme, e.g. 'neo-theme-neo-dark'
 * @returns {String}
 */
function landingUrl(devmode, theme) {
    const url = new URL(devmode, 'http://capture.invalid/');

    url.searchParams.set('theme', theme);
    return url.pathname.slice(1) + url.search + url.hash
}

/** @summary Refuses malformed input with its recipe field, before any browser opens. */
function insist(condition, field, message) {
    if (!condition) throw new TypeError(`${field}: ${message}`)
}

/** @summary Requires a plain record containing only the named schema fields. */
function keys(value, allowed, field) {
    insist(value && typeof value === 'object' && !Array.isArray(value) &&
        [Object.prototype, null].includes(Object.getPrototypeOf(value)), field, 'expected a plain object');
    const unknown = Object.keys(value).find(key => !allowed.includes(key));
    insist(!unknown, `${field}.${unknown}`, 'unknown field')
}

/** @summary Requires a nonempty string without trimming or changing its authored meaning. */
function text(value, field) {
    insist(typeof value === 'string' && value.trim().length > 0, field, 'expected a nonempty string')
}

/** @summary Validates optional literal locator text and state assertions. */
function check(value, field) {
    keys(value, ['selector', 'text', 'value', 'count', 'minDistinctHeights', 'inRegion'], field);
    text(value.selector, `${field}.selector`);
    if (value.text !== undefined) text(value.text, `${field}.text`);
    if (value.value !== undefined) insist(typeof value.value === 'string', `${field}.value`, 'expected a string');
    if (value.inRegion !== undefined) insist(typeof value.inRegion === 'boolean', `${field}.inRegion`, 'expected a boolean');
    if (value.count !== undefined) insist(Number.isInteger(value.count) && value.count >= 0, `${field}.count`, 'expected a nonnegative integer');
    if (value.minDistinctHeights !== undefined) insist(Number.isInteger(value.minDistinctHeights) && value.minDistinctHeights >= 2, `${field}.minDistinctHeights`, 'expected an integer of at least two')
}

/** @summary Validates the small public-DOM action vocabulary, including dynamic text-based fills and right-clicks. */
function step(value, field) {
    keys(value, ['kind', 'selector', 'text', 'nth', 'value', 'fromSelector', 'key', 'x', 'y', 'button'], field);
    insist(STEP_KINDS.has(value.kind), `${field}.kind`, 'unsupported action');
    // A right-click opens a context menu; no other action takes a button
    insist(value.button === undefined || value.kind === 'click' && ['left', 'right'].includes(value.button), `${field}.button`, 'only click takes button: left or right');
    text(value.selector, `${field}.selector`);
    if (value.text !== undefined) text(value.text, `${field}.text`);
    if (value.nth !== undefined) insist(Number.isInteger(value.nth) && value.nth >= 0, `${field}.nth`, 'expected a nonnegative integer');
    for (const name of ['x', 'y']) if (value[name] !== undefined) insist(Number.isFinite(value[name]), `${field}.${name}`, 'expected a finite number');
    if (value.kind === 'fill') {
        insist((typeof value.value === 'string') !== (value.fromSelector !== undefined), field, 'fill needs exactly one value or fromSelector');
        if (value.fromSelector !== undefined) text(value.fromSelector, `${field}.fromSelector`)
    } else insist(value.value === undefined && value.fromSelector === undefined, field, 'only fill takes value/fromSelector');
    if (value.kind === 'press') text(value.key, `${field}.key`);
    else insist(value.key === undefined, `${field}.key`, 'only press takes key');
    insist(value.kind === 'scroll' || value.x === undefined && value.y === undefined, field, 'only scroll takes x/y');
    if (value.kind === 'scroll') insist(value.x !== undefined || value.y !== undefined, field, 'scroll needs x or y')
}

/**
 * @summary Validates the tile list: workbench entries named by their `examples/` path, or `{path, width, height}`
 * when the component should take that size for its capture. A tile shows its crop about 175 px wide, so a wide
 * component's text shrinks with it; a narrower capture keeps that text legible.
 * @param {Array<String|Object>|undefined} value Raw `tiles` of the manifest.
 * @returns {Object[]} Tiles with a filename-safe id, the path, its devmode URL and any capture size.
 */
function tileList(value) {
    if (value === undefined) return [];
    insist(Array.isArray(value), 'manifest.tiles', 'expected an array of examples/ paths or {path, width, height} entries');
    const ids = new Set();
    return value.map((entry, i) => {
        const field = `manifest.tiles[${i}]`;
        typeof entry === 'string' || keys(entry, ['path', 'width', 'height'], field);
        const {path: tilePath, ...size} = typeof entry === 'string' ? {path: entry} : entry;
        insist(typeof tilePath === 'string' && /^examples(\/[a-zA-Z0-9_-]+)+$/.test(tilePath), field, 'expected an examples/ path');
        for (const [name, length] of Object.entries(size)) {
            insist(Number.isInteger(length) && length >= 80 && length <= 640, `${field}.${name}`, 'expected an integer from 80 to 640 CSS px')
        }
        const id = tilePath.slice('examples/'.length).replaceAll('/', '-');
        insist(!ids.has(id), field, 'duplicate tile');
        ids.add(id);
        return {id, path: tilePath, url: `${tilePath}/index.html`, ...size}
    })
}

/**
 * @summary Adds a tile for every catalog component record the frozen list does not name, at its component's own
 * size: a new tile needs its record, never an entry in the manifest.
 * @param {Object[]} listed Validated tiles from {@link tileList}.
 * @param {Object[]} catalog Canonical catalog records.
 * @returns {Object[]} The listed tiles, then the catalog's other component records as tiles, in catalog order.
 */
function catalogTiles(listed, catalog) {
    const paths = new Set(listed.map(tile => tile.path)),
          ids   = new Set(listed.map(tile => tile.id)),
          added = [];

    for (const record of catalog) {
        if (record.kind !== 'component') continue;

        const tilePath = record.sourceUrl ?? record.urls?.devmode?.replace(/\/index\.html$/, '');

        if (paths.has(tilePath)) continue;
        insist(typeof tilePath === 'string' && /^examples(\/[a-zA-Z0-9_-]+)+$/.test(tilePath), `catalog.${record.id}.sourceUrl`, 'expected an examples/ path');
        const id = tilePath.slice('examples/'.length).replaceAll('/', '-');
        insist(!ids.has(id), `catalog.${record.id}.sourceUrl`, 'duplicate tile');
        paths.add(tilePath);
        ids.add(id);
        added.push({id, path: tilePath, url: `${tilePath}/index.html`})
    }

    return [...listed, ...added]
}

/**
 * @summary Validates raw recipes and returns detached recipes with catalog-derived family, URL and name.
 * The capture opens the record's `urls.devmode`, which is also the visitor's Dev mode launch link.
 * A recipe needs a declared family. A tile (`kind: 'component'`) takes its crop from the `tiles` list. A covered card
 * without a recipe, in any family, gets a landing entry (`landing: true`) per scheme in `PAIR_THEMES`: its cover is the
 * frame a visitor lands on, dark under the base file name and light as its `-light` partner, opened on the scheme's
 * first theme and accepted on any theme it `accepts`; its catalog id names the cover file under a recipe's rule.
 * @param {Object} manifest Raw version1 recipe manifest.
 * @param {Object[]} catalog The catalog's records, from `readExampleCatalog()`.
 * @returns {Object} Validated manifest; recipes carry derived `family`, `url` and `name`, tiles their `id` and `url`.
 */
export function validateCaptureRecipes(manifest, catalog) {
    keys(manifest, ['version', 'families', 'suffix', 'recipes', 'tiles'], 'manifest');
    insist(manifest.version === 1, 'manifest.version', 'expected 1');
    insist(Array.isArray(manifest.families) && manifest.families.length > 0, 'manifest.families', 'expected a nonempty array');
    manifest.families.forEach((family, i) => text(family, `manifest.families[${i}]`));
    insist(new Set(manifest.families).size === manifest.families.length, 'manifest.families', 'duplicate family');
    insist(typeof manifest.suffix === 'string' && /^[a-zA-Z0-9_-]+$/.test(manifest.suffix), 'manifest.suffix', 'expected a filename-safe suffix');
    insist(Array.isArray(manifest.recipes) && Array.isArray(catalog), 'manifest.recipes', 'recipes and catalog must be arrays');
    const records = new Map(catalog.map(record => [record.id, record]));
    insist(records.size === catalog.length, 'catalog', 'duplicate catalog id');
    const ids = new Set(), recipes = manifest.recipes.map((recipe, index) => {
        const field = `recipes[${index}]`;
        keys(recipe, ['id', 'viewport', 'theme', 'state', 'dependencies', 'ready', 'steps', 'after', 'region'], field);
        insist(typeof recipe.id === 'string' && FILENAME_ID.test(recipe.id), `${field}.id`, 'expected a filename-safe catalog id');
        insist(!ids.has(recipe.id), `${field}.id`, 'duplicate recipe id');
        ids.add(recipe.id);
        const record = records.get(recipe.id);
        insist(record, `${field}.id`, 'unknown catalog id');
        insist(manifest.families.includes(record.family), `${field}.id`, 'record is outside declared families');
        text(record.urls?.devmode, `catalog.${recipe.id}.urls.devmode`);
        keys(recipe.viewport, ['width', 'height'], `${field}.viewport`);
        for (const axis of ['width', 'height']) insist(Number.isInteger(recipe.viewport[axis]) && recipe.viewport[axis] > 0, `${field}.viewport.${axis}`, 'expected a positive integer');
        insist(['dark', 'default'].includes(recipe.theme), `${field}.theme`, 'expected dark or default');
        text(recipe.state, `${field}.state`);
        for (const name of ['ready', 'steps', 'after']) insist(Array.isArray(recipe[name]), `${field}.${name}`, 'expected an array');
        insist(recipe.ready.length > 0 && recipe.after.length > 0, field, 'ready and after must name state assertions');
        recipe.ready.forEach((item, i) => check(item, `${field}.ready[${i}]`));
        recipe.after.forEach((item, i) => check(item, `${field}.after[${i}]`));
        recipe.steps.forEach((item, i) => step(item, `${field}.steps[${i}]`));
        if (recipe.dependencies !== undefined) {
            insist(Array.isArray(recipe.dependencies), `${field}.dependencies`, 'expected public URL strings');
            recipe.dependencies.forEach((item, i) => {
                text(item, `${field}.dependencies[${i}]`);
                let url;
                try { url = new URL(item) } catch { insist(false, `${field}.dependencies[${i}]`, 'expected an absolute public HTTP URL') }
                insist(['http:', 'https:'].includes(url.protocol) && !url.username && !url.password, `${field}.dependencies[${i}]`, 'expected an HTTP URL without credentials')
            })
        }
        const region = recipe.region;
        if (region === 'viewport') {
            const {width, height} = recipe.viewport;
            insist(width >= WIDTH && width <= 1440 && width * HEIGHT === height * WIDTH,
                `${field}.viewport`, 'full viewport requires a 16:9 frame 640 to 1440 CSS pixels wide')
        } else {
            keys(region, region?.selector !== undefined ? ['selector', 'anchor', 'offsetX', 'offsetY', 'width', 'height'] : ['x', 'y', 'width', 'height'], `${field}.region`);
            insist(region.width === WIDTH && region.height === HEIGHT, `${field}.region`, 'capture region must be 640x360 CSS pixels');
            if (region.selector !== undefined) {
                text(region.selector, `${field}.region.selector`);
                insist(['top-left', 'center'].includes(region.anchor), `${field}.region.anchor`, 'expected top-left or center');
                for (const name of ['offsetX', 'offsetY']) if (region[name] !== undefined) insist(Number.isFinite(region[name]), `${field}.region.${name}`, 'expected a finite number')
            } else for (const axis of ['x', 'y']) insist(Number.isFinite(region[axis]) && region[axis] >= 0, `${field}.region.${axis}`, 'expected a nonnegative coordinate')
        }
        return {...structuredClone(recipe), family: record.family, url: record.urls.devmode, name: record.name || record.id}
    });
    for (const record of catalog) {
        if (record.kind !== 'component' && record.image && !ids.has(record.id) && !/^https?:\/\//i.test(record.urls?.devmode || '')) {
            insist(typeof record.id === 'string' && FILENAME_ID.test(record.id), `catalog.${record.id}.id`, 'expected a filename-safe catalog id');
            text(record.urls?.devmode, `catalog.${record.id}.urls.devmode`);
            for (const {scheme, variant, themes} of PAIR_THEMES) {
                recipes.push({id: record.id, ...structuredClone(LANDING), theme: scheme === 'dark' ? 'dark' : 'default', variant, accepts: [...themes], landing: true, family: record.family, url: landingUrl(record.urls.devmode, themes[0]), name: record.name || record.id})
            }
        }
    }
    return {...structuredClone(manifest), recipes, tiles: catalogTiles(tileList(manifest.tiles), catalog)}
}

/**
 * @summary Selects one tile by its path, or every validated tile in listed order.
 * @param {Object} manifest Validated manifest from validateCaptureRecipes.
 * @param {String} [tile] One `examples/` path.
 * @returns {Object[]} Selected tiles; refuses an unknown path or an empty list.
 */
export function selectTiles(manifest, tile) {
    const selected = manifest.tiles.filter(entry => tile === undefined || entry.path === tile);
    insist(selected.length > 0, 'selection', 'no matching tiles');
    return selected
}

/**
 * @summary Selects one record, one family, or every validated recipe in authored order. A run of one family or of all
 * keeps to the declared families; one named record is reached in any family.
 * @param {Object} manifest Validated manifest from validateCaptureRecipes.
 * @param {Object} options Optional mutually exclusive record/family selection.
 * @returns {Object[]} Selected recipes; refuses an unknown or empty explicit selection.
 */
export function selectCaptureRecipes(manifest, {record, family} = {}) {
    if (record !== undefined) text(record, 'selection.record');
    if (family !== undefined) text(family, 'selection.family');
    insist(!(record && family), 'selection', 'use --record or --family, not both');
    const selected = manifest.recipes.filter(recipe => record ? recipe.id === record :
        manifest.families.includes(recipe.family) && (!family || recipe.family === family));
    insist(selected.length > 0, 'selection', 'no matching capture recipes');
    return selected
}

/** @summary Builds literal case-insensitive text locators without treating recipe text as a pattern. */
function locator(page, entry) {
    let result = page.locator(entry.selector);
    if (entry.text !== undefined) result = result.filter({hasText: new RegExp(entry.text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'i')});
    return result
}

/** @summary Waits for asserted public DOM state; no network-idle or fixed-time sleeps. */
async function assertions(page, entries, clip) {
    for (const entry of entries) {
        const target = locator(page, entry);
        if (entry.count !== undefined) await expect(target).toHaveCount(entry.count, {timeout: 15000});
        else await expect(target.first()).toBeVisible({timeout: 15000});
        if (entry.value !== undefined) await expect(target.first()).toHaveValue(entry.value, {timeout: 15000});
        if (entry.inRegion && clip) await expect.poll(async () => {
            const box = await target.first().boundingBox();
            return !!box && box.x >= clip.x && box.y >= clip.y &&
                box.x + box.width <= clip.x + clip.width && box.y + box.height <= clip.y + clip.height
        }, {timeout: 15000, message: `${entry.selector}: required detail must fit inside the capture region`}).toBe(true);
        if (entry.minDistinctHeights !== undefined) await expect.poll(async () => target.evaluateAll((nodes, area) => {
            const bounds = area ?? {x: 0, y: 0, width: innerWidth, height: innerHeight},
                heights  = nodes.map(node => node.getBoundingClientRect()).filter(box => box.height > 0 &&
                    box.top >= bounds.y && box.bottom <= bounds.y + bounds.height &&
                    box.right > bounds.x && box.left < bounds.x + bounds.width);
            return new Set(heights.map(box => Math.round(box.height))).size
        }, clip), {timeout: 15000}).toBeGreaterThanOrEqual(entry.minDistinctHeights)
    }
}

/** @summary Executes trusted user-like actions and records the resolved value of dynamic fills. */
async function actions(page, entries) {
    const performed = [];
    for (const entry of entries) {
        const target = locator(page, entry).nth(entry.nth ?? 0);
        let   value  = entry.value;
        if (entry.kind === 'fill' && entry.fromSelector !== undefined) {
            await expect(page.locator(entry.fromSelector).first()).toBeVisible();
            value = (await page.locator(entry.fromSelector).first().innerText()).trim();
            insist(value.length > 0, entry.fromSelector, 'dynamic fill text is empty')
        }
        if (entry.kind === 'click') await target.click({button: entry.button ?? 'left'});
        else if (entry.kind === 'dblclick') await target.dblclick();
        else if (entry.kind === 'fill') await target.fill(value);
        else if (entry.kind === 'press') await target.press(entry.key);
        else if (entry.kind === 'wait') await target.waitFor({state: 'visible'});
        else await target.evaluate((node, position) => {
            if (position.x !== undefined) node.scrollLeft = position.x;
            if (position.y !== undefined) node.scrollTop = position.y
        }, {x: entry.x, y: entry.y});
        performed.push({...entry, ...(entry.kind === 'fill' ? {resolvedValue: value} : {})})
    }
    return performed
}

/** @summary Resolves an authored region against its visible DOM anchor and aligns its origin to CSS pixels. */
async function captureRegion(page, region, viewport) {
    let x = region.x, y = region.y;
    if (region.selector !== undefined) {
        const target = page.locator(region.selector).first();
        await expect(target).toBeVisible();
        let previous;
        await expect.poll(async () => {
            const box = await target.boundingBox();
            if (!box) return false;
            x = box.x + (region.anchor === 'center' ? (box.width - WIDTH) / 2 : 0) + (region.offsetX ?? 0);
            y = box.y + (region.anchor === 'center' ? (box.height - HEIGHT) / 2 : 0) + (region.offsetY ?? 0);
            const signature = JSON.stringify([box.x, box.y, box.width, box.height].map(value => Math.round(value * 2))),
                stable      = signature === previous,
                animating   = await target.evaluate(node => node.classList.contains('animated-hiding-showing') ||
                    node.getAnimations().some(animation => animation.playState === 'running' || animation.pending));
            previous = signature;
            return stable && !animating && x >= 0 && y >= 0 && x + WIDTH <= viewport.width && y + HEIGHT <= viewport.height
        }, {timeout: 15000, message: `${region.selector}: waiting for a stable capture region inside the viewport`}).toBe(true)
    }
    const clip = {x: Math.round(x), y: Math.round(y), width: WIDTH, height: HEIGHT};
    insist(clip.x >= 0 && clip.y >= 0 && clip.x + WIDTH <= viewport.width && clip.y + HEIGHT <= viewport.height, 'region', 'capture lies outside the viewport; correct the recipe');
    return clip
}

/**
 * @summary Fits a component's content box into a padded tile-aspect region inside its stage. The padding gives way
 * before the content does: a blank stage, or a component that no tile-aspect region inside the stage can hold, is
 * refused rather than published cropped.
 * @param {Object|null} content Union of the component's content boxes: `left`, `top`, `right`, `bottom` (CSS px).
 * @param {Object} stage The stage's box: `x`, `y`, `width`, `height` (CSS px).
 * @returns {Object} The region's `x`, `y`, `width` and `height` (CSS px).
 */
export function fitTileRegion(content, stage) {
    insist(content && content.right - content.left >= 8 && content.bottom - content.top >= 8, 'tile', 'the stage component renders nothing');
    const aspect = TILE_MIN.width / TILE_MIN.height,
        cw       = content.right - content.left,
        ch       = content.bottom - content.top,
        width    = Math.round(Math.min(Math.max(cw + 2 * TILE_PADDING, (ch + 2 * TILE_PADDING) * aspect, TILE_MIN.width), stage.width, stage.height * aspect)),
        height   = Math.round(width / aspect),
        x        = Math.round(Math.min(Math.max((content.left + content.right) / 2 - width / 2, stage.x), stage.x + stage.width - width)),
        y        = Math.round(Math.min(Math.max((content.top + content.bottom) / 2 - height / 2, stage.y), stage.y + stage.height - height));
    // One pixel of slack absorbs rounding; anything more is content the tile would cut
    insist(x <= content.left + 1 && y <= content.top + 1 && x + width >= content.right - 1 && y + height >= content.bottom - 1, 'tile',
        `the ${Math.round(cw)}×${Math.round(ch)} component does not fit a tile-aspect region inside its ${Math.round(stage.width)}×${Math.round(stage.height)} stage`);
    return {x, y, width, height}
}

/** @summary Waits until the stage component holds its box with no animation running inside it. */
async function settle(target) {
    let previous;
    await expect.poll(async () => {
        const box = await target.boundingBox();
        if (!box) return false;
        const signature = JSON.stringify([box.x, box.y, box.width, box.height].map(value => Math.round(value * 2))),
            stable      = signature === previous,
            animating   = await target.evaluate(node => node.getAnimations({subtree: true}).some(animation => animation.playState === 'running' || animation.pending));
        previous = signature;
        return stable && !animating
    }, {timeout: 15000, message: 'waiting for the stage component to settle'}).toBe(true)
}

/**
 * @summary Measures the settled stage component's content and its stage. Content is the union of leaves, media, text
 * and decorated boxes; a decorated wrapper as large as the stage says nothing about where the component is.
 * @returns {Promise<Object>} `content` ({left, top, right, bottom}, null when blank) and `stage` ({x, y, width, height}), in CSS px.
 */
async function tileMeasure(page, target) {
    await settle(target);
    const content = await target.evaluate(node => {
        const stage = node.parentElement.getBoundingClientRect(), stageArea = stage.width * stage.height;
        let   rect  = null;
        for (const el of [node, ...node.querySelectorAll('*')]) {
            const box = el.getBoundingClientRect(), style = getComputedStyle(el);
            if (box.width < 2 || box.height < 2 || style.visibility === 'hidden') continue;
            const decorated = style.backgroundImage !== 'none' || style.boxShadow !== 'none' || parseFloat(style.borderTopWidth) > 0 ||
                    !/^(transparent|rgba\(0, 0, 0, 0\))$/.test(style.backgroundColor),
                content   = el.matches('canvas, svg, img, video, iframe, input, textarea, select, progress, meter') ||
                    [...el.childNodes].some(child => child.nodeType === 3 && child.textContent.trim()) ||
                    !['none', 'normal'].includes(getComputedStyle(el, '::before').content);
            if (!content && !(decorated && (!el.childElementCount || box.width * box.height < 0.9 * stageArea))) continue;
            // The stage clips its overflow, so only the part inside it shows; an off-screen text measurer shows nothing
            const left = Math.max(box.left, stage.left), top = Math.max(box.top, stage.top),
                right  = Math.min(box.right, stage.right), bottom = Math.min(box.bottom, stage.bottom);
            if (right - left < 2 || bottom - top < 2) continue;
            rect = rect ? {left: Math.min(rect.left, left), top: Math.min(rect.top, top), right: Math.max(rect.right, right), bottom: Math.max(rect.bottom, bottom)}
                        : {left, top, right, bottom}
        }
        return rect
    });
    return {content, stage: await page.locator('.neo-example-container').first().boundingBox()}
}

/**
 * @summary Fits one region for a tile's whole pair: the union of the component's content in every theme, inside the
 * stage area all themes share, so the crops line up and neither cuts what its theme draws larger.
 * @param {Object[]} measures One {@link tileMeasure} result per theme.
 * @returns {Object} The region's `x`, `y`, `width` and `height` (CSS px).
 */
export function pairTileRegion(measures) {
    const boxes = measures.map(({content}) => content),
        stages  = measures.map(({stage}) => stage),
        x       = Math.max(...stages.map(stage => stage.x)),
        y       = Math.max(...stages.map(stage => stage.y));
    return fitTileRegion(boxes.every(Boolean) ? {
        left : Math.min(...boxes.map(box => box.left)),  top   : Math.min(...boxes.map(box => box.top)),
        right: Math.max(...boxes.map(box => box.right)), bottom: Math.max(...boxes.map(box => box.bottom))
    } : null, {x, y, width: Math.min(...stages.map(stage => stage.x + stage.width)) - x, height: Math.min(...stages.map(stage => stage.y + stage.height)) - y})
}

/**
 * @summary Switches a workbench to the first theme of a PAIR_THEMES pass it offers. Its switch cycles through
 * `offered`, so a click is sent only while that theme is inactive: a workbench already on it needs none.
 * @param {String[]} offered The page's `Neo.config.themes`, which the workbench's theme switch cycles through.
 * @param {String} scheme The pass: `dark` or `light`.
 * @param {Function} themeOf Resolves the theme the stage shows.
 * @param {Function} next Clicks the switch and resolves once the stage shows another theme.
 * @returns {Promise<String>} The applied theme.
 */
export async function applyTileTheme(offered, scheme, themeOf, next) {
    insist(Array.isArray(offered) && offered.length > 0, 'tile', 'the page reports no themes');
    const {themes} = PAIR_THEMES.find(pass => pass.scheme === scheme),
        wanted     = themes.find(theme => offered.includes(theme));
    insist(wanted, 'tile', `the workbench offers no ${scheme} theme (${themes.join(', ')})`);
    for (let i = 0; i < offered.length && await themeOf() !== wanted; i++) await next();
    const theme = await themeOf();
    insist(theme === wanted, 'tile', `the theme switch never reached ${wanted}`);
    return theme
}

/**
 * @summary Runs in the page: the theme the app shows, the first of its `Neo.config.themes` on `<body>` or inside it, or
 * `null` before one is applied. A body viewport carries its theme on `<body>` itself, and a theme switch's own
 * `neo-themeswitcher` class is no theme.
 * @returns {String|null}
 */
function shownTheme() {
    const themes = globalThis.Neo?.config?.themes ?? [];
    for (const node of [document.body, ...document.body.querySelectorAll('[class*="neo-theme-"]')]) {
        const theme = [...node.classList].find(cls => themes.includes(cls));
        if (theme) return theme
    }
    return null
}

/**
 * @summary Runs in the page, or on the document given: whether the app's view has mounted, as an element child of
 * `<body>` that is shown and covers part of the frame. A stylesheet can set the theme on `<body>` before the App worker
 * mounts the view, so a theme alone is no frame; the main thread's own measuring nodes are hidden or parked off it.
 * @param {Document} [doc=document]
 * @returns {Boolean}
 */
export function viewMounted(doc = document) {
    const view = doc.defaultView;
    return [...doc.body.children].some(node => {
        if (['LINK', 'NOSCRIPT', 'SCRIPT', 'STYLE', 'TEMPLATE'].includes(node.tagName)) return false;
        const style = view.getComputedStyle(node), box = node.getBoundingClientRect();
        return style.display !== 'none' && style.visibility !== 'hidden' &&
            Math.min(box.right, view.innerWidth) > Math.max(box.left, 0) && Math.min(box.bottom, view.innerHeight) > Math.max(box.top, 0)
    })
}

/**
 * @summary Records, from before its navigation, the requests a page has open and when its network last moved, as
 * Playwright reports them, plus the requests Chromium names a SharedWorker's start-up (`Sec-Fetch-Dest: sharedworker`,
 * which only its own network events carry): the ledger {@link networkQuiet} reads.
 * @param {Object} page
 * @returns {Promise<{lastActivity: Number, pending: Set<Object>, startups: Map<String, String>}>}
 */
export async function trackNetwork(page) {
    const cdp     = await page.context().newCDPSession(page),
          network = {lastActivity: Date.now(), pending: new Set(), startups: new Map()},
          urls    = new Map(),
          workers = new Set(),
          settle  = request => {network.pending.delete(request); network.lastActivity = Date.now()},
          name    = requestId => urls.has(requestId) && workers.has(requestId) && network.startups.set(requestId, urls.get(requestId));

    page.on('request', request => {network.pending.add(request); network.lastActivity = Date.now()});
    page.on('requestfinished', settle);
    page.on('requestfailed', settle);
    cdp.on('Network.requestWillBeSent', ({requestId, request}) => {urls.set(requestId, request.url); name(requestId)});
    cdp.on('Network.requestWillBeSentExtraInfo', ({requestId, headers}) => {
        Object.entries(headers).some(([key, value]) => key.toLowerCase() === 'sec-fetch-dest' && value === 'sharedworker') && workers.add(requestId) && name(requestId)
    });
    await cdp.send('Network.enable');

    return network
}

/**
 * @summary Waits until no request has been open for NETWORK_QUIET_MS, apart from the start-up scripts of SharedWorkers:
 * requests Chromium names one, for a worker the browser runs. Chromium hands that script to the worker, and the page
 * never sees it finish, so Playwright's `networkidle` never arrives for a SharedWorker example. A URL only passes as
 * often as Chromium named it, so a request that shares a worker's URL keeps the page waiting, as does any other open
 * request, and a timeout names both kinds.
 * @param {{lastActivity: Number, pending: Set<Object>, startups: Map<String, String>}} network The ledger of
 * {@link trackNetwork}
 * @param {Function} sharedWorkerUrls Resolves the script URLs of the SharedWorkers the browser runs
 * @param {Number} [timeout=15000]
 * @returns {Promise<String[]>} The start-up scripts it did not wait for
 */
export async function networkQuiet(network, sharedWorkerUrls, timeout=15000) {
    const deadline = Date.now() + timeout;
    let open, startups;

    while (true) {
        const workers = new Set(await sharedWorkerUrls()),
              named   = new Map();

        [...network.startups.values()].filter(url => workers.has(url)).forEach(url => named.set(url, (named.get(url) ?? 0) + 1));
        open     = [];
        startups = [];

        network.pending.forEach(request => {
            const url = request.url();

            named.get(url) > 0 ? (named.set(url, named.get(url) - 1), startups.push(url)) : open.push(url)
        });

        if (!open.length && Date.now() - network.lastActivity >= NETWORK_QUIET_MS) {
            return startups
        }

        if (Date.now() > deadline) {
            throw new Error(`landing: the network never went quiet; open: ${open.join(', ') || 'none'}; SharedWorker start-up scripts not waited for: ${startups.join(', ') || 'none'}`)
        }

        await new Promise(resolve => setTimeout(resolve, 100))
    }
}

/**
 * @summary Waits until a landing frame holds still: the network is quiet ({@link networkQuiet}), the app shows a
 * configured theme ({@link shownTheme}), its view has mounted ({@link viewMounted}), and the DOM has not changed for
 * LANDING_QUIET_MS. One rule for every example, with no selector of its own; an example that never settles fails,
 * because its landing state is not a frame a cover can show.
 * @param {Object} page
 * @param {{lastActivity: Number, pending: Set<Object>, startups: Map<String, String>}} network The ledger of
 * {@link trackNetwork}, started before the page navigated
 * @param {Function} [sharedWorkerUrls] Resolves the script URLs of the SharedWorkers the browser runs
 * @returns {Promise<String[]>} The SharedWorker start-up scripts it did not wait for
 */
export async function landingReady(page, network, sharedWorkerUrls=async () => []) {
    const startups = await networkQuiet(network, sharedWorkerUrls);
    await page.waitForFunction(shownTheme, null, {polling: 250, timeout: 15000}).catch(error => {throw new Error(`landing: no configured theme shows on <body> or inside it (${error.message.split('\n')[0]})`)});
    await page.waitForFunction(viewMounted, undefined, {polling: 250, timeout: 15000}).catch(error => {throw new Error(`landing: no view mounted in <body> (${error.message.split('\n')[0]})`)});
    await page.waitForFunction(quietMs => new Promise(resolve => {
        let timer;
        const observer = new MutationObserver(() => {clearTimeout(timer); timer = setTimeout(settled, quietMs)}),
              settled  = () => {observer.disconnect(); resolve(true)};
        observer.observe(document.documentElement, {attributes: true, characterData: true, childList: true, subtree: true});
        timer = setTimeout(settled, quietMs)
    }), LANDING_QUIET_MS, {polling: 250, timeout: 15000}).catch(error => {throw new Error(`landing: the frame never held still for ${LANDING_QUIET_MS} ms (${error.message.split('\n')[0]})`)});

    return startups
}

/**
 * @summary Waits for fonts, stylesheets and media that can paint inside the capture, including native video controls.
 * @param {Object} page Playwright page
 * @param {Object} clip Capture region in viewport coordinates
 * @param {Number} [timeout=15000] Maximum wait for styles and visible media in milliseconds
 */
export async function paintReady(page, clip, timeout=15000) {
    await page.evaluate(async () => { await document.fonts.ready });
    await expect.poll(() => page.evaluate(rect => {
        if ([...document.querySelectorAll('link[rel="stylesheet"]')].some(link => !link.sheet)) return false;

        const images = [...document.images].filter(image => !image.complete || !image.naturalWidth),
              videos = [...document.querySelectorAll('video')].filter(video => (video.currentSrc || video.querySelector('source[src]')) &&
                  (video.readyState < 2 || !video.videoWidth || video.controls && !video.paused && Number(document.timeline?.currentTime ?? 2000) < 1800)),
              pending = [...images, ...videos];
        if (!pending.length) return true;

        // A lazy image behind a scroller's edge can stay unloaded for the life of the page.
        return new Promise(resolve => {
            const observer = new IntersectionObserver(entries => {
                observer.disconnect();
                const inCapture = entries.some(({intersectionRect: box}) => box.width > 0 && box.height > 0 &&
                    box.right > rect.x && box.bottom > rect.y && box.left < rect.x + rect.width && box.top < rect.y + rect.height);
                resolve(entries.length === pending.length && !inCapture)
            });
            pending.forEach(el => observer.observe(el))
        })
    }, clip), {timeout, message: 'waiting for styles and media inside the capture region to paint'}).toBe(true)
}

/** @summary Reads JPEG frame dimensions so device-scale output is checked rather than assumed. */
function jpegSize(bytes) {
    insist(bytes[0] === 255 && bytes[1] === 216, 'screenshot', 'not a JPEG');
    let offset = 2;
    while (offset + 8 < bytes.length) {
        insist(bytes[offset] === 255, 'screenshot', 'invalid JPEG marker');
        const marker = bytes[offset + 1];
        if ([192, 193, 194].includes(marker)) return {width: bytes.readUInt16BE(offset + 7), height: bytes.readUInt16BE(offset + 5)};
        offset += 2 + bytes.readUInt16BE(offset + 2)
    }
    throw new Error('screenshot: JPEG frame dimensions absent')
}

/** @summary Captures a checked state in a fresh context; failures never publish a cover file. */
async function capture(browser, recipe, manifest, baseUrl, output) {
    const url = new URL(recipe.url, baseUrl);
    insist(url.origin === baseUrl.origin && ['http:', 'https:'].includes(url.protocol), recipe.id, 'canonical devmode URL must resolve on the base origin');
    const fullViewport      = recipe.region === 'viewport',
          deviceScaleFactor = fullViewport ? WIDTH * DPR / recipe.viewport.width : DPR,
          context           = await browser.newContext({viewport: recipe.viewport, deviceScaleFactor, ...(recipe.theme === 'dark' ? {colorScheme: 'dark'} : {})}),
          row               = {id: recipe.id, name: recipe.name, url: url.href, viewport: recipe.viewport, deviceScaleFactor, theme: recipe.theme, state: recipe.state, dependencies: recipe.dependencies ?? [], ready: recipe.ready, steps: recipe.steps, after: recipe.after, requestedRegion: recipe.region};
    let cdp;
    try {
        const page = await context.newPage(), errors = [], network = await trackNetwork(page);
        page.setDefaultTimeout(15000);
        page.on('pageerror', error => errors.push(error.message));
        await page.goto(url.href, {waitUntil: 'domcontentloaded', timeout: 30000});
        if (recipe.landing) {
            cdp = await browser.newBrowserCDPSession();
            row.sharedWorkerStartups = await landingReady(page, network, async () => (await cdp.send('Target.getTargets')).targetInfos.filter(({type}) => type === 'shared_worker').map(({url}) => url))
        } else {
            await assertions(page, recipe.ready)
        }
        if (recipe.landing) {
            // An example that ignores `?theme=` opens on its first theme: a frame of the other scheme is no cover of this one
            row.openedTheme = await page.evaluate(shownTheme);
            insist(recipe.accepts.includes(row.openedTheme), recipe.id, `opened on ${row.openedTheme}, not on ${recipe.accepts.join(' or ')}`)
        }
        row.steps = await actions(page, recipe.steps);
        await assertions(page, recipe.after);
        row.region = fullViewport ? {x: 0, y: 0, ...recipe.viewport} : await captureRegion(page, recipe.region, recipe.viewport);
        await paintReady(page, row.region);
        row.actualDevicePixelRatio = await page.evaluate(() => window.devicePixelRatio);
        insist(Math.abs(row.actualDevicePixelRatio - deviceScaleFactor) < 1e-6, recipe.id, 'unexpected device pixel ratio');
        // A full screenshot keeps Chromium's backdrop sampling intact around blurred modal masks.
        const frame = fullViewport ? {} : {clip: row.region};
        for (const quality of QUALITIES) {
            await assertions(page, recipe.after, row.region);
            insist(!errors.length, recipe.id, `page errors: ${errors.join('; ')}`);
            const bytes = await page.screenshot({type: 'jpeg', quality, ...frame, scale: 'device', animations: 'disabled', caret: 'hide'}),
                  size  = jpegSize(bytes);
            insist(size.width === WIDTH * DPR && size.height === HEIGHT * DPR, recipe.id, 'JPEG must be 1280x720');
            if (bytes.length > MAX_BYTES) continue;
            const relative = `devmode/${recipe.id}-${manifest.suffix}${recipe.variant ?? ''}.jpg`, file = path.join(output, relative);
            await fs.writeFile(file, bytes, {flag: 'wx'});
            return {...row, status: 'captured', image: relative, quality, ...size, bytes: bytes.length, sha256: crypto.createHash('sha256').update(bytes).digest('hex')}
        }
        throw new Error(`JPEG exceeds ${MAX_BYTES} bytes at qualities ${QUALITIES.join('/')}`)
    } catch (error) {
        return {...row, status: 'failed', error: error.message}
    } finally {
        await cdp?.detach().catch(() => {});
        await context.close()
    }
}

/** @summary Shoots a region as the best-quality JPEG within MAX_BYTES, checked at the device pixel ratio. */
async function shoot(page, clip, id) {
    for (const quality of QUALITIES) {
        const bytes = await page.screenshot({type: 'jpeg', quality, clip, scale: 'device', animations: 'disabled', caret: 'hide'}), size = jpegSize(bytes);
        insist(size.width === clip.width * DPR && size.height === clip.height * DPR, id, 'JPEG must be the region at the device pixel ratio');
        if (bytes.length <= MAX_BYTES) return {bytes, quality, ...size}
    }
    throw new Error(`JPEG exceeds ${MAX_BYTES} bytes at qualities ${QUALITIES.join('/')}`)
}

/**
 * @summary Writes a pair's images, or none of them. A file is this call's once its exclusive open (`wx`) succeeds; when a
 * later open or write fails, the files this call opened are removed before the error goes on, so a failed pair leaves no
 * half behind. A path whose open failed was never this call's and stays, whatever the error.
 * @param {String} output The run's output directory
 * @param {Object[]} shots `{image, bytes}` each, `image` relative to `output`
 * @param {Function} [open=fs.open]
 * @returns {Promise<void>}
 */
export async function writePair(output, shots, open=fs.open) {
    const created = [];

    try {
        for (const {image, bytes} of shots) {
            const file   = path.join(output, image),
                  handle = await open(file, 'wx');

            created.push(file);

            try {
                await handle.writeFile(bytes)
            } finally {
                await handle.close()
            }
        }
    } catch (error) {
        await Promise.all(created.map(file => fs.rm(file, {force: true})));
        throw error
    }
}

/**
 * @summary Crops one workbench entry's component with the whole workbench on its dark theme, then on its light theme,
 * in one region that holds the component in both, so the pair lines up. A failure in either publishes neither tile.
 * @returns {Promise<Object[]|Object>} One report row per theme, or one failed row.
 */
async function captureTile(browser, tile, manifest, baseUrl, output) {
    const url = new URL(tile.url, baseUrl);
    insist(url.origin === baseUrl.origin && ['http:', 'https:'].includes(url.protocol), tile.id, 'devmode URL must resolve on the base origin');
    const context = await browser.newContext({viewport: TILE_VIEWPORT, deviceScaleFactor: DPR, colorScheme: 'dark'}),
        row       = {id: tile.id, kind: 'tile', path: tile.path, url: url.href, viewport: TILE_VIEWPORT, deviceScaleFactor: DPR};
    try {
        const page  = await context.newPage(), errors = [], measures = [], shots = [],
            target  = page.locator('.neo-example-container > *').first(),
            themeOf = () => page.locator('.neo-workbench-stage').first().evaluate(node => [...(node.closest('[class*="neo-theme-"]')?.classList ?? [])].find(cls => cls.startsWith('neo-theme-')) ?? null),
            next    = async () => {const before = await themeOf(); await page.locator('.neo-button-theme-switch').first().click(); await expect.poll(themeOf).not.toBe(before)};
        page.setDefaultTimeout(15000);
        page.on('pageerror', error => errors.push(error.message));
        await page.goto(url.href, {waitUntil: 'domcontentloaded', timeout: 30000});
        await expect(target).toBeVisible();
        const offered = await page.evaluate(() => globalThis.Neo?.config?.themes),
            // The switch repaints the whole workbench, stage surface included, so each pass presents the stage anew: the
            // component alone (the stage's other items, a field's states, keep their place unpainted), at the entry's
            // capture size, which narrows a wide component so its text stays legible at the tile's width
            present = async scheme => {
                const theme = await applyTileTheme(offered, scheme, themeOf, next);
                await page.locator('.neo-example-container > :not(:first-child)').evaluateAll(nodes => nodes.forEach(node => node.style.visibility = 'hidden'));
                if (tile.width || tile.height) await target.evaluate((node, {width, height}) => {
                    width  && Object.assign(node.style, {width : `${width}px`,  maxWidth : `${width}px`, minWidth : 0});
                    height && Object.assign(node.style, {height: `${height}px`, maxHeight: `${height}px`, minHeight: 0})
                }, {width: tile.width, height: tile.height});
                return theme
            };
        if (tile.width || tile.height) row.size = {width: tile.width, height: tile.height};
        for (const {scheme} of PAIR_THEMES) { await present(scheme); measures.push(await tileMeasure(page, target)) }
        row.region = pairTileRegion(measures);
        // The page still shows the last pass's theme, so the shots run backwards and the first needs no switch
        for (const {scheme, variant} of [...PAIR_THEMES].reverse()) {
            const theme = await present(scheme);
            await settle(target);
            await paintReady(page, row.region);
            shots.unshift({theme, image: `devmode/tiles/${tile.id}-${manifest.suffix}${variant}.jpg`, ...await shoot(page, row.region, tile.id)})
        }
        insist(!errors.length, tile.id, `page errors: ${errors.join('; ')}`);
        await writePair(output, shots);
        return shots.map(({bytes, ...shot}) => ({...row, status: 'captured', ...shot, bytes: bytes.length, sha256: crypto.createHash('sha256').update(bytes).digest('hex')}))
    } catch (error) {
        return {...row, status: 'failed', error: error.message}
    } finally { await context.close() }
}

/** @summary Escapes report text for the local contact sheet at card width. */
function html(value) { return String(value).replace(/[&<>"']/g, char => ({'&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;'}[char])) }

