const engineRoot = path.resolve(import.meta.dirname, '../../../..'),
      fixture    = path.join(import.meta.dirname, 'fixtures/pipeline-interceptors'),
      linked     = ['acorn', 'astring', 'commander', 'esbuild', 'fs-extra',
          'html-minifier-terser', 'terser', 'webpack', 'webpack-hook-plugin', ...BROWSER_BUNDLES],
      mime       = {'.css': 'text/css', '.html': 'text/html', '.js': 'text/javascript', '.json': 'application/json', '.mjs': 'text/javascript'};

/** @summary Packs the current engine and builds a consumer using only installed production build entrypoints. */
function prepareWorkspace(root) {
    const workspace = path.join(root, 'workspace'), engine = path.join(workspace, 'node_modules/neo.mjs');
    const packed    = withComposedNpmIgnore(engineRoot, () => execFileSync('npm', [
        'pack', '--json', '--ignore-scripts', '--loglevel=error', '--pack-destination', root
    ], {cwd: engineRoot, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024}));

    fs.mkdirSync(engine, {recursive: true});
    execFileSync('tar', ['-xzf', path.join(root, JSON.parse(packed)[0].filename), '-C', engine, '--strip-components=1']);
    expect(fs.lstatSync(engine).isSymbolicLink(), 'the consumer executes the extracted npm package').toBe(false);
    expect(fs.existsSync(path.join(engine, 'dist')), 'browser dependencies must be generated by the installed engine').toBe(false);
    fs.cpSync(fixture, path.join(workspace, 'apps/probe'), {recursive: true});

    const write = (relative, value) => {
        const file = path.join(workspace, relative);
        fs.mkdirSync(path.dirname(file), {recursive: true});
        fs.writeFileSync(file, typeof value === 'string' ? value : JSON.stringify(value, null, 4))
    };
    write('package.json', {name: 'pipeline-interceptor-consumer', version: '0.0.0', type: 'module', private: true,
        neo: {esmSourceRoots: ['resources']}});
    // Empty theme-build outputs: these workers still read their normal map even with themes disabled.
    write('resources/theme-map.json', {Neo: {}, apps: {}});
    for (const environment of ['development', 'production']) {
        write(`dist/${environment}/resources/theme-map.json`, {Neo: {}, apps: {}})
    }
    // create-app owns its workspace MicroLoader; preserve its production import resolution.
    write('src/MicroLoader.mjs', fs.readFileSync(path.join(engine, 'src/MicroLoader.mjs'), 'utf8'));

    for (const name of linked) {
        const target = path.join(workspace, 'node_modules', name);
        fs.mkdirSync(path.dirname(target), {recursive: true});
        fs.symlinkSync(path.join(engineRoot, 'node_modules', name), target, 'junction')
    }
    // webpack copies this asset package as a directory, matching an ordinary consumer installation.
    fs.cpSync(fs.realpathSync(path.join(engineRoot, 'node_modules/@fortawesome/fontawesome-free')),
        path.join(workspace, 'node_modules/@fortawesome/fontawesome-free'), {recursive: true});

    const run = args => {
        const result = spawnSync(process.execPath, args, {cwd: workspace, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024});
        expect(result.error, args.join(' ')).toBeUndefined();
        expect(result.status, `${args.join(' ')}\n${result.stdout}\n${result.stderr}`).toBe(0)
    };
    for (const name of BROWSER_BUNDLES) run([path.join(engine, `buildScripts/build/${name}.mjs`)]);
    run([path.join(engine, 'buildScripts/build/esmodules.mjs')]);

    for (const environment of ['development', 'production']) {
        for (const worker of ['main', 'app', 'data', 'vdom']) {
            const suffix = worker === 'main' ? 'main' : worker === 'app' ? 'appworker' : 'worker';
            const args   = [path.join(workspace, 'node_modules/webpack/bin/webpack.js'), '--config',
                path.join(engine, `buildScripts/webpack/${environment}/webpack.config.${suffix}.mjs`)];
            if (worker !== 'main') args.push('--env', 'insideNeo=false');
            if (worker !== 'main' && worker !== 'app') args.push('--env', `worker=${worker}`);
            run(args)
        }
    }
    return workspace
}

/** @summary Serves real consumer assets and records HTTP effects independently of the app's receipt. */
function createServer(workspace, requests) {
    return http.createServer((request, response) => {
        const pathname = decodeURIComponent(new URL(request.url, 'http://localhost').pathname);
        if (pathname === '/favicon.ico') return response.writeHead(204).end();
        const record = {path: pathname, status: 200};
        requests.push(record);
        response.setHeader('Cache-Control', 'no-store');

        if (pathname.startsWith('/api/')) {
            Object.assign(record, {method: request.method, order: request.headers['x-neo-order'] ?? null,
                realm: request.headers['x-neo-realm'] ?? null});
            const sequence = requests.filter(item => item.path === pathname).length;
            if (pathname.endsWith('/stream')) {
                const body = [1, 2, 3].map(id => JSON.stringify({id, sequence})).join('\n') + '\n';
                response.writeHead(200, {'Content-Type': 'application/x-ndjson', 'Content-Length': Buffer.byteLength(body)});
                response.end(body);
                return
            }
            record.status = pathname.endsWith('/failure') ? 503 : 200;
            response.writeHead(record.status, {'Content-Type': 'application/json'});
            response.end(JSON.stringify({order: record.order, realm: record.realm, sequence}));
            return
        }

        const file = path.resolve(workspace, '.' + pathname);
        if (!file.startsWith(workspace + path.sep) || !fs.statSync(file, {throwIfNoEntry: false})?.isFile()) {
            record.status = 404;
            response.writeHead(404).end();
            return
        }
        response.writeHead(200, {'Content-Type': mime[path.extname(file)] ?? 'application/octet-stream'});
        fs.createReadStream(file).pipe(response)
    })
}

/** @summary Checks asynchronous hook execution, realm ownership, cache behavior and streamed delivery. */
function assertRealm(receipt, requests, realm) {
    const received = name => requests.filter(item => item.path === `/api/${realm}/${name}`);
    expect(receipt.realm).toBe(realm);
    if (realm === 'data') expect(receipt.remoteId).toBeTruthy();
    expect(received('control')).toHaveLength(1);
    expect(receipt.unchanged.data).toEqual({order: null, realm: null, sequence: 1});
    expect(receipt.unchanged.responseTrace).toBeUndefined();
    expect(receipt.unchanged.shapeTrace).toBeUndefined();

    const stages = [
        [receipt.first, ['global', 'local']],
        [receipt.localChanged, ['global', 'local-next']],
        [receipt.globalChanged, ['global-next', 'local-next']]
    ];
    expect(received('cached')).toHaveLength(3);
    for (const [index, [value, order]] of stages.entries()) {
        expect(received('cached')[index]).toMatchObject({method: 'GET', order: order.join(','), realm});
        expect(value.data).toEqual({order: order.join(','), realm, sequence: index + 1});
        expect(value.responseTrace).toEqual(order);
        expect(value.shapeTrace).toEqual(order);
        expect(value.responseRealm).toBe(realm);
        expect(value.shapeRealm).toBe(realm)
    }
    expect(receipt.cached, 'a cache hit retains the final shape without running response hooks twice').toEqual(receipt.first);

    expect(received('failure')).toHaveLength(2);
    expect(receipt.recovered).toMatchObject({ok: true, recovered: 'recover', errorRealm: realm,
        data: {realm, order: 'recover', sequence: 1}, shapeTrace: ['recover'], shapeRealm: realm});
    expect(receipt.rejected, 'undefined from responseError retains a rejection').toBe(true);
    expect(receipt.remoteRejections).toEqual(['consumer hook refused', 'consumer hook refused']);
    for (const telemetry of [false, true]) {
        expect(received(`uncloneable-${telemetry}`), 'a hook refusal settles without retrying transport').toHaveLength(1)
    }

    expect(received('stream')).toHaveLength(2);
    for (const request of received('stream')) expect(request).toMatchObject({order: 'stream-global,stream-local', realm});
    const {stream} = receipt;
    expect(stream.firstBatchCount, 'the first read awaits every asynchronous row transformation').toBe(3);
    expect(stream.batches).toHaveLength(6);
    expect(stream.batches.flat().map(row => row.id)).toEqual([1, 2, 3, 1, 2, 3]);
    for (const [index, batch] of stream.batches.entries()) {
        expect(batch).toEqual([{id: index % 3 + 1, sequence: index < 3 ? 1 : 2,
            shapeTrace: ['stream-global', 'stream-local'], shapeRealm: realm}])
    }
    expect(stream.progress.length, 'Data progress is forwarded to the App-side Pipeline').toBeGreaterThanOrEqual(2);
    for (const event of stream.progress) {
        expect(event.loaded).toBeGreaterThan(0);
        expect(event.total).toBeGreaterThanOrEqual(event.loaded)
    }
    expect(stream.first).toMatchObject({success: true, count: 3});
    expect(stream.again).toMatchObject({success: true, count: 3});
    expect(stream.first.shapeTrace, 'terminal stream summaries bypass row hooks').toBeUndefined()
}

test.describe('consumer Pipeline interceptors through production worker loading', () => {
    test.describe.configure({mode: 'serial'});
    let origin, root, server;
    const requests = [];

    test.beforeAll(async () => {
        test.setTimeout(600000);
        root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'neo-pipeline-interceptor-workspace-')));
        const workspace = prepareWorkspace(root);
        server = createServer(workspace, requests);
        await new Promise((resolve, reject) => {
            server.once('error', reject);
            server.listen(0, '127.0.0.1', resolve)
        });
        origin = `http://127.0.0.1:${server.address().port}`
    });

    test.afterAll(async () => {
        if (server) {
            await new Promise((resolve, reject) => {
                server.close(error => error ? reject(error) : resolve());
                server.closeAllConnections()
            })
        }
        root && fs.rmSync(root, {recursive: true, force: true})
    });

    for (const layout of ['', 'dist/esm/', 'dist/development/', 'dist/production/']) {
        test(`${layout || 'source/'}: custom consumer hooks execute in App and Data`, async ({page}, testInfo) => {
            test.setTimeout(90000);
            requests.length = 0;
            const errors = [];
            page.on('pageerror', error => errors.push(error.message));
            await page.goto(`${origin}/${layout}apps/probe/index.html`);
            await page.waitForFunction(() => Boolean(globalThis.Neo?.worker?.App?.getConfigs));
            let receipt;
            await expect.poll(async () => {
                receipt = await page.evaluate(() => Neo.worker.App.getConfigs({id: 'pipeline-interceptor-probe', keys: 'receipt'}));
                return receipt?.status
            }, {timeout: 60000, message: 'normal consumer startup completes the worker execution probe'}).toMatch(/complete|failed/);

            await testInfo.attach('consumer-receipt', {body: JSON.stringify({receipt, requests, errors}, null, 2), contentType: 'application/json'});
            expect(receipt.status, receipt.error).toBe('complete');
            for (const realm of ['app', 'data']) assertRealm(receipt[realm], requests, realm);
            expect(errors).toEqual([]);
            expect(requests.filter(item => item.status >= 400 && !item.path.startsWith('/api/'))).toEqual([]);
            if (layout) {
                expect(requests.filter(item => item.path.includes('/node_modules/neo.mjs/')),
                    'built workers and consumer modules execute from the emitted tree').toEqual([])
            } else {
                expect(requests.map(item => item.path)).toContain('/apps/probe/Handler.mjs')
            }
        })
    }
});
